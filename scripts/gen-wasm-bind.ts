/**
 * Derives the wasm-bindgen binding module from the Node-API binding source.
 *
 * The modular Node-API source is recomposed before the browser module reuses its function bodies
 * through `wasm_shim.rs` and rewrites only attributes and signatures that differ between runtimes.
 */
import { readFile, writeFile } from 'fs/promises';
import { resolve } from 'path';

const rootDir = resolve(import.meta.dir, '..');
const source = resolve(rootDir, 'bindings/galfus-native/src/napi_bind.rs');
const target = resolve(rootDir, 'bindings/galfus-native/src/wasm_bind.rs');
const MODULE_SOURCES = [
  'napi_platform.rs',
  'napi_multiverse.rs',
  'napi_resources_animation.rs',
  'napi_realm_3d.rs',
  'napi_realm_2d.rs'
];

/** Hand-written functions that replace generated ones (see `wasm_attach.rs`). */
const SKIPPED_FUNCTIONS = ['multiverse_attach_window'];

function snakeToCamel(name: string): string {
  return name.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

function stripModuleDeclaration(source: string): string {
  return source.replace(
    /#\[path = "napi_[^"]+\.rs"\]\nmod napi_\w+;\npub use napi_\w+::\*;\n*/g,
    ''
  );
}

function stripModulePrelude(source: string): string {
  return source.replace(/^\/\/![^\n]*\n\nuse super::\*;\n\n/, '');
}

async function readNodeApiSource(): Promise<string> {
  const rootSource = stripModuleDeclaration(await readFile(source, 'utf-8'));
  const moduleSources = await Promise.all(
    MODULE_SOURCES.map(async (file) => {
      return stripModulePrelude(
        await readFile(resolve(rootDir, `bindings/galfus-native/src/${file}`), 'utf-8')
      );
    })
  );
  return `${rootSource}\n${moduleSources.join('\n')}`;
}

function transform(input: string): string {
  let out = input;

  out = out.replace(
    /^use napi::JsUnknown;\nuse napi::bindgen_prelude::\*;\nuse napi_derive::napi;\n/m,
    'use wasm_bindgen::prelude::*;\n\nuse crate::wasm_shim::*;\n'
  );

  // Window attachment is asynchronous in the browser (see `wasm_attach.rs`).
  out = out.replace(/\n\s*attach_window_to_multiverse,/, '');

  // Helpers provided by the shim instead.
  out = out.replace(/fn js_to_c_string[\s\S]*?\n}\n\n/, '');

  for (const name of SKIPPED_FUNCTIONS) {
    out = out.replace(
      new RegExp(`(?:///[^\\n]*\\n)*#\\[napi[^\\n]*\\]\\npub fn ${name}\\b[\\s\\S]*?\\n}\\n\\n`),
      ''
    );
  }

  // Attributes: default napi names are lowerCamelCase of the Rust name.
  out = out.replace(/#\[napi\]\npub fn (\w+)/g, (_, fn: string) => {
    return `#[wasm_bindgen(js_name = "${snakeToCamel(fn)}")]\npub fn ${fn}`;
  });
  out = out.replace(/#\[napi\(js_name = ("[^"]+")\)\]/g, '#[wasm_bindgen(js_name = $1)]');

  // 64-bit integers cross the JS boundary as plain numbers, not BigInt.
  out = out.replace(/Option<i64>/g, 'Option<f64>').replace(/: i64\b/g, ': f64');
  out = out.replace(
    /u64::try_from\(batch_id\)/g,
    'Ok::<u64, std::convert::Infallible>(batch_id as u64)'
  );

  // `env: Env` becomes a local unit value so bodies stay untouched.
  out = out.replace(/pub fn \w+\([^{]*?\{/g, (signature) => {
    if (!/\benv: Env\b/.test(signature)) return signature;
    const stripped = signature
      .replace(/\n\s*env: Env,/, '')
      .replace(/\benv: Env,\s*/, '')
      .replace(/\benv: Env\b/, '');
    return `${stripped}\n    let env = Env;`;
  });

  // The shim factory returns a JavaScript value, so it must not use Rust's conventional `new`.
  out = out.replace(/Error::new\(/g, 'Error::from_reason(');

  return `// Generated by scripts/gen-wasm-bind.ts from napi_bind.rs. Do not edit directly.\n${out}`;
}

const generated = transform(await readNodeApiSource());
await writeFile(target, generated, 'utf-8');
console.log(`✔ Generated ${target}`);
