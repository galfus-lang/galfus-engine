import { API_FUNCTIONS, FunctionSpec, ParamSpec } from './spec.ts';

function mapCType(type: string): string {
  switch (type) {
    case 'void':
      return 'void';
    case 'i32':
      return 'int32_t';
    case 'u32':
      return 'uint32_t';
    case 'f32':
      return 'float';
    case 'f64':
      return 'double';
    case 'bool':
      return 'bool';
    case 'string_in':
      return 'const char*';
    case 'string_out':
      return 'char*';
    default:
      return 'void*';
  }
}

function renderParams(params: ParamSpec[]): string {
  if (params.length === 0) return 'void';
  return params
    .map((p) => `${mapCType(p.type)} ${p.name.replace(/([A-Z])/g, '_$1').toLowerCase()}`)
    .join(', ');
}

export function generateCHeader(): string {
  const lines: string[] = [
    '/* Automatically generated by Galfus Engine codegen. Do not edit directly. */',
    '#ifndef GALFUS_H',
    '#define GALFUS_H',
    '',
    '#include <stdint.h>',
    '#include <stdbool.h>',
    '',
    '#ifdef __cplusplus',
    'extern "C" {',
    '#endif',
    '',
    '/** Frees a string previously returned by a Galfus API function. */',
    'void galfus_string_free(char* ptr);',
    ''
  ];

  for (const fn of API_FUNCTIONS) {
    lines.push(`/** ${fn.doc} */`);
    lines.push(`${mapCType(fn.returnType)} ${fn.cName}(${renderParams(fn.params)});`);
    lines.push('');
  }

  lines.push('#ifdef __cplusplus');
  lines.push('}');
  lines.push('#endif');
  lines.push('');
  lines.push('#endif /* GALFUS_H */');
  lines.push('');

  return lines.join('\n');
}
