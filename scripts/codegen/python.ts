import { API_FUNCTIONS, FunctionSpec, ParamSpec } from './spec.ts';

function mapPythonCType(type: string): string {
  switch (type) {
    case 'i32':
      return 'ctypes.c_int32';
    case 'u32':
      return 'ctypes.c_uint32';
    case 'bool':
      return 'ctypes.c_bool';
    case 'string_in':
      return 'ctypes.c_char_p';
    case 'string_out':
      return 'ctypes.c_void_p';
    default:
      return 'ctypes.c_void_p';
  }
}

function toSnakeCase(str: string): string {
  return str.replace(/([A-Z])/g, '_$1').toLowerCase();
}

export function generatePython(): string {
  const lines: string[] = [
    '"""Automatically generated by Galfus Engine codegen. Do not edit directly."""',
    'from __future__ import annotations',
    '',
    'import ctypes',
    'import json',
    'import os',
    'import platform',
    'from typing import Any, Dict, List, Optional',
    '',
    'def _load_library() -> ctypes.CDLL:',
    '    system = platform.system()',
    '    if system == "Windows":',
    '        lib_name = "galfus.dll"',
    '    elif system == "Darwin":',
    '        lib_name = "libgalfus_native.dylib"',
    '    else:',
    '        lib_name = "libgalfus_native.so"',
    '',
    '    # Check adjacent directories and standard cargo build outputs',
    '    candidate_paths = [',
    '        lib_name,',
    '        os.path.join(os.path.dirname(__file__), lib_name),',
    '        os.path.join(os.path.dirname(__file__), "../../build/cargo-target/debug", lib_name),',
    '        os.path.join(os.path.dirname(__file__), "../../build/cargo-target/release", lib_name),',
    '    ]',
    '    for path in candidate_paths:',
    '        if os.path.exists(path):',
    '            return ctypes.CDLL(path)',
    '    try:',
    '        return ctypes.CDLL(lib_name)',
    '    except OSError as err:',
    '        raise RuntimeError(f"Could not locate Galfus library ({lib_name}): {err}")',
    '',
    '_lib = _load_library()',
    '',
    '# String deallocator signature',
    '_lib.galfus_string_free.argtypes = [ctypes.c_void_p]',
    '_lib.galfus_string_free.restype = None',
    '',
    'def _consume_string(ptr: Optional[int]) -> str:',
    '    if not ptr:',
    '        return ""',
    '    try:',
    '        return ctypes.string_at(ptr).decode("utf-8")',
    '    finally:',
    '        _lib.galfus_string_free(ptr)',
    '',
    'class GalfusError(Exception):',
    '    """Exception raised when a Galfus engine call fails."""',
    '    pass',
    ''
  ];

  for (const fn of API_FUNCTIONS) {
    const pyFuncName = toSnakeCase(fn.methodName);

    // Setup argtypes and restype
    if (fn.params.length > 0) {
      const argtypes = fn.params.map((p) => mapPythonCType(p.type)).join(', ');
      lines.push(`_lib.${fn.cName}.argtypes = [${argtypes}]`);
    } else {
      lines.push(`_lib.${fn.cName}.argtypes = []`);
    }

    if (fn.returnType === 'string_out') {
      lines.push(`_lib.${fn.cName}.restype = ctypes.c_void_p`);
    } else if (fn.returnType === 'i32') {
      lines.push(`_lib.${fn.cName}.restype = ctypes.c_int32`);
    } else if (fn.returnType === 'u32') {
      lines.push(`_lib.${fn.cName}.restype = ctypes.c_uint32`);
    } else {
      lines.push(`_lib.${fn.cName}.restype = None`);
    }

    lines.push('');

    // Signature
    const typedParams: string[] = [];
    for (const p of fn.params) {
      const pName = toSnakeCase(p.name);
      if (
        p.type === 'string_in' &&
        (p.name.toLowerCase().includes('json') || p.name.toLowerCase().includes('config'))
      ) {
        typedParams.push(`${pName}: Dict[str, Any] | str`);
      } else if (p.type === 'string_in') {
        typedParams.push(`${pName}: str`);
      } else if (p.type === 'i32' || p.type === 'u32') {
        typedParams.push(`${pName}: int`);
      } else if (p.type === 'bool') {
        typedParams.push(`${pName}: bool`);
      } else {
        typedParams.push(`${pName}: Any`);
      }
    }

    let returnAnnotation = 'None';
    if (fn.returnsJson) {
      returnAnnotation = 'Any';
    } else if (fn.returnType === 'string_out') {
      returnAnnotation = 'str';
    } else if (fn.params.some((p) => p.name === 'configJson' || p.name === 'config')) {
      returnAnnotation = 'int';
    }

    lines.push(`def ${pyFuncName}(${typedParams.join(', ')}) -> ${returnAnnotation}:`);
    lines.push(`    """${fn.doc}"""`);

    // Prepare argument conversions
    const callArgs: string[] = [];
    for (const p of fn.params) {
      const pName = toSnakeCase(p.name);
      if (
        p.type === 'string_in' &&
        (p.name.toLowerCase().includes('json') || p.name.toLowerCase().includes('config'))
      ) {
        lines.push(
          `    _${pName}_raw = json.dumps(${pName}) if isinstance(${pName}, dict) else str(${pName})`
        );
        lines.push(`    _${pName}_bytes = _${pName}_raw.encode("utf-8")`);
        callArgs.push(`_${pName}_bytes`);
      } else if (p.type === 'string_in') {
        lines.push(`    _${pName}_bytes = ${pName}.encode("utf-8")`);
        callArgs.push(`_${pName}_bytes`);
      } else {
        callArgs.push(pName);
      }
    }

    if (fn.returnsJson) {
      lines.push(`    json_str = _consume_string(_lib.${fn.cName}(${callArgs.join(', ')}))`);
      lines.push(`    if not json_str:`);
      lines.push(`        return [] if "events" in "${fn.methodName}".lower() else {}`);
      lines.push(`    return json.loads(json_str)`);
    } else if (fn.returnType === 'string_out') {
      lines.push(`    return _consume_string(_lib.${fn.cName}(${callArgs.join(', ')}))`);
    } else if (fn.returnType === 'i32') {
      lines.push(`    res = _lib.${fn.cName}(${callArgs.join(', ')})`);
      lines.push(`    if res != 0:`);
      lines.push(`        raise GalfusError(f"${fn.methodName} failed: {get_last_error()}")`);
      const configParam = fn.params.find((p) => p.name === 'configJson' || p.name === 'config');
      if (configParam) {
        const pName = toSnakeCase(configParam.name);
        lines.push(`    if isinstance(${pName}, dict) and "id" in ${pName}:`);
        lines.push(`        return ${pName}["id"]`);
        lines.push(`    return 0`);
      }
    } else {
      lines.push(`    return _lib.${fn.cName}(${callArgs.join(', ')})`);
    }

    lines.push('');
  }

  return lines.join('\n');
}
