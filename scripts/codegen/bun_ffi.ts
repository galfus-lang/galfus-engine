import { API_FUNCTIONS, FunctionSpec, ParamSpec } from './spec.ts';

function mapFFIType(type: string): string {
  switch (type) {
    case 'i32':
      return 'FFIType.i32';
    case 'u32':
      return 'FFIType.u32';
    case 'f32':
      return 'FFIType.f32';
    case 'f64':
      return 'FFIType.f64';
    case 'bool':
      return 'FFIType.bool';
    case 'string_in':
    case 'string_out':
      return 'FFIType.ptr';
    case 'void':
      return 'FFIType.void';
    default:
      return 'FFIType.ptr';
  }
}

export function generateBunFFI(): string {
  const lines: string[] = [
    '/* Automatically generated by Galfus Engine codegen. Do not edit directly. */',
    'import { dlopen, FFIType, CString, ptr } from "bun:ffi";',
    'import { existsSync } from "fs";',
    'import { resolve, dirname } from "path";',
    'import type {',
    '  PlatformCapabilities,',
    '  WindowConfig,',
    '  PlatformEvent,',
    '  GamepadInfo,',
    '  GalfusEngine,',
    '} from "../typescript/galfus.ts";',
    '',
    'function locateLibrary(): string {',
    "  const isWindows = process.platform === 'win32';",
    "  const isMac = process.platform === 'darwin';",
    '  const libName = isWindows',
    "    ? 'galfus.dll'",
    '    : isMac',
    "    ? 'libgalfus_native.dylib'",
    "    : 'libgalfus_native.so';",
    '',
    "  const baseDir = typeof import.meta.dir === 'string' ? import.meta.dir : process.cwd();",
    '  const candidates = [',
    '    resolve(baseDir, libName),',
    "    resolve(baseDir, '../../build/cargo-target/debug', libName),",
    "    resolve(baseDir, '../../build/cargo-target/release', libName),",
    "    resolve(baseDir, '../..', libName),",
    '  ];',
    '',
    '  for (const candidate of candidates) {',
    '    if (existsSync(candidate)) {',
    '      return candidate;',
    '    }',
    '  }',
    '  return libName;',
    '}',
    '',
    'export class GalfusError extends Error {',
    '  constructor(message: string) {',
    '    super(message);',
    "    this.name = 'GalfusError';",
    '  }',
    '}',
    '',
    'export class GalfusBun implements GalfusEngine {',
    '  private _lib: any;',
    '',
    '  constructor(customLibPath?: string) {',
    '    const path = customLibPath ?? locateLibrary();',
    '    this._lib = dlopen(path, {',
    '      galfus_string_free: {',
    '        args: [FFIType.ptr],',
    '        returns: FFIType.void,',
    '      },'
  ];

  // Dynamically declare FFI symbols from API_FUNCTIONS
  for (const fn of API_FUNCTIONS) {
    const args = fn.params.map((p) => mapFFIType(p.type)).join(', ');
    const returns = mapFFIType(fn.returnType);
    lines.push(`      ${fn.cName}: {`);
    lines.push(`        args: [${args}],`);
    lines.push(`        returns: ${returns},`);
    lines.push('      },');
  }

  lines.push(
    '    });',
    '  }',
    '',
    '  private consumeString(rawPtr: any): string {',
    "    if (!rawPtr) return '';",
    '    try {',
    '      return new CString(rawPtr).toString();',
    '    } finally {',
    '      this._lib.symbols.galfus_string_free(rawPtr);',
    '    }',
    '  }',
    '',
    '  private toCString(str: string): Uint8Array {',
    "    return Buffer.from(str + '\\0', 'utf-8');",
    '  }',
    ''
  );

  // Dynamically generate class methods from API_FUNCTIONS
  for (const fn of API_FUNCTIONS) {
    const isConfigCall = fn.params.some((p) => p.name === 'configJson' || p.name === 'config');

    // Method parameter types
    const paramsList: string[] = [];
    for (const p of fn.params) {
      if (p.name === 'configJson' || p.name === 'config') {
        paramsList.push(`${p.name}: WindowConfig`);
      } else if (p.type === 'string_in') {
        paramsList.push(`${p.name}: string`);
      } else if (p.type === 'i32' || p.type === 'u32' || p.type === 'f32' || p.type === 'f64') {
        paramsList.push(`${p.name}: number`);
      } else if (p.type === 'bool') {
        paramsList.push(`${p.name}: boolean`);
      } else {
        paramsList.push(`${p.name}: any`);
      }
    }

    // Return type annotation
    let retType = 'void';
    if (fn.returnsJson) {
      if (fn.methodName === 'platformGetCapabilities') {
        retType = 'PlatformCapabilities';
      } else if (fn.methodName === 'platformPumpEvents') {
        retType = 'PlatformEvent[]';
      } else if (fn.methodName === 'gamepadGetConnected') {
        retType = 'GamepadInfo[]';
      } else {
        retType = 'any';
      }
    } else if (fn.returnType === 'string_out') {
      retType = 'string';
    } else if (isConfigCall) {
      retType = 'number';
    } else if (fn.returnType === 'i32' || fn.returnType === 'u32') {
      retType = 'void';
    }

    lines.push(`  /** ${fn.doc} */`);
    lines.push(`  ${fn.methodName}(${paramsList.join(', ')}): ${retType} {`);

    // Prepare argument conversions
    const ffiArgs: string[] = [];
    for (const p of fn.params) {
      if (p.name === 'configJson' || p.name === 'config') {
        lines.push(`    const _${p.name}_buf = this.toCString(JSON.stringify(${p.name}));`);
        ffiArgs.push(`ptr(_${p.name}_buf)`);
      } else if (p.type === 'string_in') {
        lines.push(`    const _${p.name}_buf = this.toCString(${p.name});`);
        ffiArgs.push(`ptr(_${p.name}_buf)`);
      } else {
        ffiArgs.push(p.name);
      }
    }

    const callExpr = `this._lib.symbols.${fn.cName}(${ffiArgs.join(', ')})`;

    if (fn.returnsJson) {
      lines.push(`    const rawPtr = ${callExpr};`);
      lines.push(`    const jsonStr = this.consumeString(rawPtr);`);
      lines.push(`    if (!jsonStr) {`);
      lines.push(`      return ${retType.endsWith('[]') ? '[]' : '{}'} as ${retType};`);
      lines.push(`    }`);
      lines.push(`    return JSON.parse(jsonStr) as ${retType};`);
    } else if (fn.returnType === 'string_out') {
      lines.push(`    const rawPtr = ${callExpr};`);
      lines.push(`    return this.consumeString(rawPtr);`);
    } else if (fn.returnType === 'i32') {
      lines.push(`    const res = ${callExpr};`);
      lines.push(`    if (res !== 0) {`);
      lines.push(
        `      throw new GalfusError(\`${fn.methodName} failed: \${this.getLastError()}\`);`
      );
      lines.push(`    }`);
      if (isConfigCall) {
        const configParam = fn.params.find((p) => p.name === 'configJson' || p.name === 'config');
        lines.push(`    return ${configParam?.name}.id;`);
      }
    } else {
      lines.push(`    return ${callExpr};`);
    }

    lines.push('  }');
    lines.push('');
  }

  lines.push('}', '', 'export const galfus = new GalfusBun();', '');

  return lines.join('\n');
}
