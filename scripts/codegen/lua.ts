import { API_FUNCTIONS, FunctionSpec, ParamSpec } from './spec.ts';

function mapLuaCParam(p: ParamSpec): string {
  switch (p.type) {
    case 'i32':
      return `int32_t ${p.name}`;
    case 'u32':
      return `uint32_t ${p.name}`;
    case 'f32':
      return `float ${p.name}`;
    case 'f64':
      return `double ${p.name}`;
    case 'bool':
      return `bool ${p.name}`;
    case 'string_in':
      return `const char* ${p.name}`;
    case 'string_out':
      return `char* ${p.name}`;
    default:
      return `void* ${p.name}`;
  }
}

function mapLuaCReturn(type: string): string {
  switch (type) {
    case 'void':
      return 'void';
    case 'i32':
      return 'int32_t';
    case 'u32':
      return 'uint32_t';
    case 'f32':
      return 'float';
    case 'f64':
      return 'double';
    case 'bool':
      return 'bool';
    case 'string_out':
    case 'string_in':
      return 'char*';
    default:
      return 'void*';
  }
}

function toSnakeCase(str: string): string {
  return str.replace(/([A-Z])/g, '_$1').toLowerCase();
}

export function generateLua(): string {
  const lines: string[] = [
    '-- Automatically generated by Galfus Engine codegen. Do not edit directly.',
    'local ffi = require("ffi")',
    '',
    'ffi.cdef[[',
    '    void galfus_string_free(char* ptr);'
  ];

  for (const fn of API_FUNCTIONS) {
    const params = fn.params.length === 0 ? 'void' : fn.params.map(mapLuaCParam).join(', ');
    const ret = mapLuaCReturn(fn.returnType);
    lines.push(`    ${ret} ${fn.cName}(${params});`);
  }

  lines.push(
    ']]',
    '',
    'local function find_library()',
    '    local candidates = { "libgalfus_native.so", "./libgalfus_native.so", "galfus.dll", "libgalfus_native.dylib" }',
    '    for _, name in ipairs(candidates) do',
    '        local ok, lib = pcall(ffi.load, name)',
    '        if ok then return lib end',
    '    end',
    '    return ffi.load("libgalfus_native.so")',
    'end',
    '',
    'local clib = find_library()',
    'local M = {}',
    '',
    'local function consume_string(c_str)',
    '    if c_str == nil then return nil end',
    '    local str = ffi.string(c_str)',
    '    clib.galfus_string_free(c_str)',
    '    return str',
    'end',
    ''
  );

  for (const fn of API_FUNCTIONS) {
    const luaFuncName = toSnakeCase(fn.methodName);
    const paramNames = fn.params.map((p) => toSnakeCase(p.name)).join(', ');

    lines.push(`--- ${fn.doc}`);
    lines.push(`function M.${luaFuncName}(${paramNames})`);

    const callArgs = fn.params.map((p) => toSnakeCase(p.name)).join(', ');

    if (fn.returnType === 'string_out') {
      lines.push(`    return consume_string(clib.${fn.cName}(${callArgs}))`);
    } else if (fn.returnType === 'i32') {
      lines.push(`    local res = clib.${fn.cName}(${callArgs})`);
      lines.push(`    if res ~= 0 then`);
      lines.push(`        error("${fn.methodName} failed: " .. (M.get_last_error() or "unknown"))`);
      lines.push(`    end`);
      const hasConfig = fn.params.some((p) => p.name === 'configJson' || p.name === 'config');
      if (hasConfig) {
        lines.push(`    return 0`);
      }
    } else {
      lines.push(`    return clib.${fn.cName}(${callArgs})`);
    }

    lines.push('end');
    lines.push('');
  }

  lines.push('return M');
  lines.push('');

  return lines.join('\n');
}
