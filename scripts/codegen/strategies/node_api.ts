import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { type DataType, isJson, isJsonArray } from '../spec.ts';

function mapParamTsType(type: DataType): string {
  if (isJson(type)) {
    if (type.json === 'Transform3DDesc') {
      return `Transform3DDesc | Float32Array | number[] | string`;
    }
    if (type.json === 'Transform2DDesc') {
      return `Transform2DDesc | Float32Array | number[] | string`;
    }
    return `${type.json} | string`;
  }
  if (isJsonArray(type)) {
    return `${type.jsonArray}[] | string`;
  }
  switch (type) {
    case 'bool':
      return 'boolean';
    case 'i32':
    case 'u32':
    case 'u64':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      return 'string';
    case 'void':
      return 'void';
    case 'ptr':
      return 'any';
    default:
      return 'any';
  }
}

function mapReturnTsType(fnReturnType: DataType, hasParamFieldReturn: boolean): string {
  if (hasParamFieldReturn) {
    return 'number';
  }
  if (isJson(fnReturnType)) {
    return fnReturnType.json;
  }
  if (isJsonArray(fnReturnType)) {
    return `${fnReturnType.jsonArray}[]`;
  }
  switch (fnReturnType) {
    case 'bool':
      return 'boolean';
    case 'i32':
      return 'void';
    case 'u32':
    case 'u64':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      return 'string';
    case 'void':
      return 'void';
    default:
      return 'void';
  }
}

export class NodeApiStrategy implements CodegenStrategy {
  readonly id = 'node_api';
  readonly name = 'Node-API (N-API) Wrapper';
  readonly relativeOutputDir = 'sdk/node';
  readonly filename = 'galfus.ts';

  generate(context: CodegenContext): string {
    const BUILTIN_TS_TYPES = new Set(['number', 'string', 'boolean', 'any', 'void']);
    const importedTypes = new Set<string>(['GalfusEngine']);
    const addType = (t: string) => {
      const clean = t.replace(/\[\]$/, '').trim();
      if (!BUILTIN_TS_TYPES.has(clean)) {
        importedTypes.add(clean);
      }
    };
    for (const fn of context.functions) {
      if (isJson(fn.returnType)) addType(fn.returnType.json);
      if (isJsonArray(fn.returnType)) addType(fn.returnType.jsonArray);
      for (const p of fn.params) {
        if (isJson(p.type)) addType(p.type.json);
        if (isJsonArray(p.type)) addType(p.type.jsonArray);
      }
    }

    importedTypes.delete('ViewportRect');
    const typeImports = Array.from(importedTypes).sort().join(',\n  ');

    const lines: string[] = [
      '/* Automatically generated by Galfus Engine codegen. Do not edit directly. */',
      'import { existsSync } from "fs";',
      'import { resolve, dirname } from "path";',
      'import { ViewportRect } from "../typescript/galfus.ts";',
      `import type {`,
      `  ${typeImports}`,
      `} from "../typescript/galfus.ts";`,
      `export type {`,
      `  ${typeImports}`,
      `};`,
      `export { ViewportRect };`,
      '',
      'function locateAddon(): string {',
      "  const isWindows = process.platform === 'win32';",
      "  const isMac = process.platform === 'darwin';",
      "  const addonName = 'galfus.node';",
      '  const libName = isWindows',
      "    ? 'galfus.dll'",
      '    : isMac',
      "    ? 'libgalfus_native.dylib'",
      "    : 'libgalfus_native.so';",
      '',
      "  const baseDir = typeof import.meta.dir === 'string' ? import.meta.dir : process.cwd();",
      '  const candidates = [',
      '    resolve(baseDir, addonName),',
      "    resolve(baseDir, '../../build/cargo-target/debug', addonName),",
      "    resolve(baseDir, '../../build/cargo-target/release', addonName),",
      '    resolve(baseDir, libName),',
      "    resolve(baseDir, '../../build/cargo-target/debug', libName),",
      "    resolve(baseDir, '../../build/cargo-target/release', libName),",
      "    resolve(baseDir, '../..', libName),",
      '  ];',
      '',
      '  for (const candidate of candidates) {',
      '    if (existsSync(candidate)) {',
      '      return candidate;',
      '    }',
      '  }',
      '  return addonName;',
      '}',
      '',
      'export class GalfusError extends Error {',
      '  constructor(message: string) {',
      '    super(message);',
      "    this.name = 'GalfusError';",
      '  }',
      '}',
      '',
      'export class GalfusNode implements GalfusEngine {',
      '  private _addon: any;',
      '',
      '  constructor(customPath?: string) {',
      '    const path = customPath ?? locateAddon();',
      '    const mod: { exports: any } = { exports: {} };',
      '    process.dlopen(mod, path);',
      '    this._addon = mod.exports;',
      '  }',
      '',
      '  getLastError(): string {',
      "    return typeof this._addon.getLastError === 'function' ? this._addon.getLastError() : '';",
      '  }'
    ];

    for (const fn of context.functions) {
      if (fn.methodName === 'getLastError') continue;

      const params = fn.params
        .map((p) => `${p.name}${p.optional ? '?' : ''}: ${mapParamTsType(p.type)}`)
        .join(', ');
      const retType = mapReturnTsType(fn.returnType, !!fn.returnsParamField);

      lines.push('');
      lines.push(`  /** ${fn.doc} */`);
      lines.push(`  ${fn.methodName}(${params}): ${retType} {`);
      lines.push(`    if (typeof this._addon.${fn.methodName} !== 'function') {`);
      lines.push(
        `      throw new GalfusError("Node-API method not implemented: ${fn.methodName}");`
      );
      lines.push(`    }`);

      // Prepare call args, parsing JSON strings to objects if passed as string
      const callArgs = fn.params
        .map((p) => {
          if (isJson(p.type) || isJsonArray(p.type)) {
            return `typeof ${p.name} === 'string' ? JSON.parse(${p.name}) : ${p.name}`;
          }
          return p.name;
        })
        .join(', ');

      if (retType === 'void') {
        lines.push(`    this._addon.${fn.methodName}(${callArgs});`);
      } else {
        lines.push(`    return this._addon.${fn.methodName}(${callArgs});`);
      }
      lines.push('  }');
    }

    lines.push('}');
    lines.push('');

    return lines.join('\n');
  }
}
