import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { collectEngineTypes, engineMethodLines } from './ts_engine_methods.ts';

export class NodeApiStrategy implements CodegenStrategy {
  readonly id = 'node_api';
  readonly name = 'Node-API (N-API) Wrapper';
  readonly relativeOutputDir = 'sdk/node';
  readonly filename = 'galfus.ts';

  generate(context: CodegenContext): string {
    const importedTypes = collectEngineTypes(context);
    importedTypes.delete('ViewportRect');
    const typeImports = Array.from(importedTypes).sort().join(',\n  ');

    const lines: string[] = [
      '/* Automatically generated by Galfus Engine codegen. Do not edit directly. */',
      'import { existsSync } from "fs";',
      'import { resolve, dirname } from "path";',
      'import { fileURLToPath } from "url";',
      'import { ViewportRect } from "../typescript/galfus.ts";',
      `import type {`,
      `  ${typeImports}`,
      `} from "../typescript/galfus.ts";`,
      `export type {`,
      `  ${typeImports}`,
      `};`,
      `export { ViewportRect };`,
      '',
      'function locateAddon(): string {',
      "  const addonName = 'galfus.node';",
      '',
      "  const baseDir = typeof import.meta.dir === 'string' ? import.meta.dir : dirname(fileURLToPath(import.meta.url));",
      '  const candidates = [',
      '    resolve(baseDir, addonName),',
      "    resolve(baseDir, '../../lib', addonName),",
      "    resolve(baseDir, '../../build/cargo-target/debug', addonName),",
      "    resolve(baseDir, '../../build/cargo-target/release', addonName),",
      '  ];',
      '',
      '  for (const candidate of candidates) {',
      '    if (existsSync(candidate)) {',
      '      return candidate;',
      '    }',
      '  }',
      '  return addonName;',
      '}',
      '',
      'export class GalfusError extends Error {',
      '  constructor(message: string) {',
      '    super(message);',
      "    this.name = 'GalfusError';",
      '  }',
      '}',
      '',
      'export class GalfusNode implements GalfusEngine {',
      '  private _addon: any;',
      '',
      '  constructor(customPath?: string) {',
      '    const path = customPath ?? locateAddon();',
      '    const mod: { exports: any } = { exports: {} };',
      '    process.dlopen(mod, path);',
      '    this._addon = mod.exports;',
      '  }',
      '',
      '  getLastError(): string {',
      "    return typeof this._addon.getLastError === 'function' ? this._addon.getLastError() : '';",
      '  }'
    ];

    lines.push(...engineMethodLines(context, 'Node-API'));

    lines.push(
      '',
      '  /** Reads the inner physical size [width, height] of a Platform window. */',
      '  windowGetSize(windowId: number): [number, number] {',
      '    return this._addon.windowGetSize(windowId);',
      '  }',
      '',
      '  /** Reads the inner physical size [width, height] of a Platform window (alias for windowGetSize). */',
      '  platformGetWindowSize(windowId: number): [number, number] {',
      '    return this.windowGetSize(windowId);',
      '  }'
    );

    lines.push('}');
    lines.push('');

    return lines.join('\n');
  }
}
