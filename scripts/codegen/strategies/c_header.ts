import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { type DataType, isBuffer, isNativeStruct } from '../spec.ts';

function toSnakeCase(str: string): string {
  return str.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

function mapCType(type: DataType, isParam: boolean): string {
  if (isNativeStruct(type)) {
    return isParam ? `const Galfus${type.nativeStruct}*` : `Galfus${type.nativeStruct}*`;
  }
  if (isBuffer(type)) {
    const element = type.buffer === 'u8' ? 'uint8_t' : type.buffer === 'u32' ? 'uint32_t' : 'float';
    return isParam ? `const ${element}*` : `${element}*`;
  }
  if (typeof type === 'object') {
    return isParam ? 'const char*' : 'char*';
  }
  switch (type) {
    case 'void':
      return 'void';
    case 'bool':
      return 'bool';
    case 'i32':
      return 'int32_t';
    case 'u32':
      return 'uint32_t';
    case 'u64':
      return 'uint64_t';
    case 'f32':
      return 'float';
    case 'f64':
      return 'double';
    case 'string':
      return isParam ? 'const char*' : 'char*';
    default:
      return 'void*';
  }
}

export class CHeaderStrategy implements CodegenStrategy {
  readonly id = 'c_header';
  readonly name = 'C / C++ Header';
  readonly relativeOutputDir = 'sdk/c';
  readonly filename = 'galfus.h';

  generate(context: CodegenContext): string {
    const lines: string[] = [
      '/*',
      ' * Galfus Engine - C API Header',
      ' * Automatically generated by Galfus codegen. Do not edit directly.',
      ' */',
      '',
      '#ifndef GALFUS_H',
      '#define GALFUS_H',
      '',
      '#include <stdint.h>',
      '#include <stdbool.h>',
      '',
      '#ifdef __cplusplus',
      'extern "C" {',
      '#endif',
      '',
      '#if defined(_WIN32) || defined(__CYGWIN__)',
      '  #ifdef GALFUS_BUILD_DLL',
      '    #define GALFUS_API __declspec(dllexport)',
      '  #else',
      '    #define GALFUS_API __declspec(dllimport)',
      '  #endif',
      '#else',
      '  #define GALFUS_API __attribute__((visibility("default")))',
      '#endif',
      '',
      '/* Fixed-layout values used by hot-path APIs. Pass them by pointer; Galfus copies inputs synchronously. */',
      'typedef struct {',
      '  float position_x, position_y, position_z;',
      '  float rotation_x, rotation_y, rotation_z, rotation_w;',
      '  float scale_x, scale_y, scale_z;',
      '} GalfusTransform3D;',
      '',
      'typedef struct {',
      '  float position_x, position_y, rotation, scale_x, scale_y;',
      '  int32_t z_layer, draw_order;',
      '} GalfusTransform2D;',
      '',
      'typedef struct {',
      '  uint32_t enabled;',
      '  float target_x, target_y, target_z;',
      '  float up_x, up_y, up_z;',
      '} GalfusCameraLookAt3D;',
      '',
      'typedef struct {',
      '  float emitter_x, emitter_y, emitter_z;',
      '  float emitter_rotation_x, emitter_rotation_y, emitter_rotation_z, emitter_rotation_w;',
      '  float listener_x, listener_y, listener_z;',
      '  float listener_rotation_x, listener_rotation_y, listener_rotation_z, listener_rotation_w;',
      '  float volume, min_distance, max_distance, rolloff, speed;',
      '  uint32_t looping;',
      '} GalfusSpatialAudio;',
      '',
      '/* Platform events use a compact record plus UTF-8 text arena. Text ranges are byte offsets into text_data. */',
      'typedef struct {',
      '  uint16_t kind, event_type;',
      '  uint32_t flags, window_id, subject_id;',
      '  uint64_t id;',
      '  float values[5];',
      '  uint32_t text0_offset, text0_length, text1_offset, text1_length, text2_offset, text2_length;',
      '} GalfusPlatformEvent;',
      '',
      'typedef struct {',
      '  uint64_t batch_id;',
      '  const GalfusPlatformEvent* events;',
      '  uint32_t event_count;',
      '  const uint8_t* text_data;',
      '  uint32_t text_length;',
      '} GalfusEventBatch;',
      '',
      '/** Frees a string pointer allocated across the FFI boundary by Galfus. */',
      'GALFUS_API void galfus_string_free(char* ptr);',
      ''
    ];

    for (const fn of context.functions) {
      lines.push(`/** ${fn.doc} */`);
      const retType = mapCType(fn.returnType, false);
      const params =
        fn.params.length === 0
          ? 'void'
          : fn.params.map((p) => `${mapCType(p.type, !p.out)} ${toSnakeCase(p.name)}`).join(', ');

      lines.push(`GALFUS_API ${retType} ${fn.cName}(${params});`);
      lines.push('');
    }

    lines.push('#ifdef __cplusplus', '}', '#endif', '', '#endif /* GALFUS_H */', '');
    return lines.join('\n');
  }
}
