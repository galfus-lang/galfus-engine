import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import type { DataType } from '../spec.ts';

function toSnakeCase(str: string): string {
  return str.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

function mapCType(type: DataType, isParam: boolean): string {
  if (typeof type === 'object') {
    return isParam ? 'const char*' : 'char*';
  }
  switch (type) {
    case 'void':
      return 'void';
    case 'bool':
      return 'bool';
    case 'i32':
      return 'int32_t';
    case 'u32':
      return 'uint32_t';
    case 'u64':
      return 'uint64_t';
    case 'f32':
      return 'float';
    case 'f64':
      return 'double';
    case 'string':
      return isParam ? 'const char*' : 'char*';
    default:
      return 'void*';
  }
}

export class CHeaderStrategy implements CodegenStrategy {
  readonly id = 'c_header';
  readonly name = 'C / C++ Header';
  readonly relativeOutputDir = 'sdk/c';
  readonly filename = 'galfus.h';

  generate(context: CodegenContext): string {
    const lines: string[] = [
      '/*',
      ' * Galfus Engine - C API Header',
      ' * Automatically generated by Galfus codegen. Do not edit directly.',
      ' */',
      '',
      '#ifndef GALFUS_H',
      '#define GALFUS_H',
      '',
      '#include <stdint.h>',
      '#include <stdbool.h>',
      '',
      '#ifdef __cplusplus',
      'extern "C" {',
      '#endif',
      '',
      '#if defined(_WIN32) || defined(__CYGWIN__)',
      '  #ifdef GALFUS_BUILD_DLL',
      '    #define GALFUS_API __declspec(dllexport)',
      '  #else',
      '    #define GALFUS_API __declspec(dllimport)',
      '  #endif',
      '#else',
      '  #define GALFUS_API __attribute__((visibility("default")))',
      '#endif',
      '',
      '/** Frees a string pointer allocated across the FFI boundary by Galfus. */',
      'GALFUS_API void galfus_string_free(char* ptr);',
      ''
    ];

    for (const fn of context.functions) {
      lines.push(`/** ${fn.doc} */`);
      const retType = mapCType(fn.returnType, false);
      const params =
        fn.params.length === 0
          ? 'void'
          : fn.params.map((p) => `${mapCType(p.type, true)} ${toSnakeCase(p.name)}`).join(', ');

      lines.push(`GALFUS_API ${retType} ${fn.cName}(${params});`);
      lines.push('');
    }

    lines.push('#ifdef __cplusplus', '}', '#endif', '', '#endif /* GALFUS_H */', '');
    return lines.join('\n');
  }
}
