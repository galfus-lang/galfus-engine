import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import {
  type DataType,
  type DescSpec,
  type FieldType,
  isBuffer,
  isJson,
  isJsonArray,
  isNativeStruct
} from '../spec.ts';

function renderTsType(type: FieldType): string {
  if (typeof type === 'string') {
    return type;
  }
  if ('ref' in type) {
    return type.ref;
  }
  if ('enum' in type) {
    return type.enum.map((v) => JSON.stringify(v)).join(' | ');
  }
  if ('literal' in type) {
    return JSON.stringify(type.literal);
  }
  if ('tuple' in type) {
    return `[${type.tuple.map(renderTsType).join(', ')}]`;
  }
  if ('array' in type) {
    const inner = renderTsType(type.array);
    return inner.includes(' ') || inner.includes('|') ? `(${inner})[]` : `${inner}[]`;
  }
  if ('inline' in type) {
    const fields = Object.entries(type.inline).map(([name, spec]) => {
      const opt = spec.optional ? '?' : '';
      return `${name}${opt}: ${renderTsType(spec.type)}`;
    });
    return `{ ${fields.join('; ')} }`;
  }
  return 'unknown';
}

function renderDescriptor(desc: DescSpec): string {
  const doc = desc.doc ? `/** ${desc.doc} */\n` : '';

  if (desc.kind === 'enum') {
    const values = desc.values.map((v) => JSON.stringify(v)).join(' | ');
    return `${doc}export type ${desc.name} = ${values};`;
  }

  if (desc.kind === 'union') {
    if (
      desc.variants.length <= 3 &&
      desc.variants.every((v) => typeof v === 'string' || 'ref' in v || 'literal' in v)
    ) {
      const types = desc.variants.map((v) => renderTsType(v)).join(' | ');
      return `${doc}export type ${desc.name} = ${types};`;
    }
    const variants = desc.variants.map((v) => `  | ${renderTsType(v)}`).join('\n');
    return `${doc}export type ${desc.name} =\n${variants};`;
  }

  if (desc.kind === 'object') {
    const fields = Object.entries(desc.fields)
      .map(([name, spec]) => {
        const fieldDoc = spec.doc ? `  /** ${spec.doc} */\n` : '';
        const opt = spec.optional ? '?' : '';
        return `${fieldDoc}  ${name}${opt}: ${renderTsType(spec.type)};`;
      })
      .join('\n');

    return `${doc}export interface ${desc.name} {\n${fields}\n}`;
  }

  return '';
}

function mapParamTsType(type: DataType): string {
  if (isNativeStruct(type)) {
    return type.nativeStruct === 'SpatialAudio' ? 'SpatialAudio' : type.nativeStruct;
  }
  if (isBuffer(type)) {
    return type.buffer === 'u8'
      ? 'Uint8Array'
      : type.buffer === 'u32'
        ? 'Uint32Array'
        : 'Float32Array';
  }
  if (isJson(type)) {
    return `${type.json} | string`;
  }
  if (isJsonArray(type)) {
    return `${type.jsonArray}[] | string`;
  }
  switch (type) {
    case 'bool':
      return 'boolean';
    case 'i32':
    case 'u32':
    case 'u64':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      return 'string';
    case 'void':
      return 'void';
    case 'ptr':
      return 'any';
    default:
      return 'any';
  }
}

function mapReturnTsType(fnReturnType: DataType, hasParamFieldReturn: boolean): string {
  if (hasParamFieldReturn) {
    return 'number';
  }
  if (isJson(fnReturnType)) {
    return fnReturnType.json;
  }
  if (isJsonArray(fnReturnType)) {
    return `${fnReturnType.jsonArray}[]`;
  }
  switch (fnReturnType) {
    case 'bool':
      return 'boolean';
    case 'i32':
      return 'void';
    case 'u32':
    case 'u64':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      return 'string';
    case 'void':
      return 'void';
    default:
      return 'void';
  }
}

export class TypeScriptStrategy implements CodegenStrategy {
  readonly id = 'typescript';
  readonly name = 'TypeScript Definitions';
  readonly relativeOutputDir = 'sdk/typescript';
  readonly filename = 'galfus.ts';

  generate(context: CodegenContext): string {
    const lines: string[] = [
      '/* Automatically generated by Galfus Engine codegen. Do not edit directly. */',
      '/* Canonical shared domain types and payload specifications for Galfus Engine host bindings. */',
      '',
      '/** Value object used for frequent 3D transform updates. */',
      'export interface Transform3D {',
      '  position: [number, number, number];',
      '  rotation?: [number, number, number, number];',
      '  scale?: [number, number, number];',
      '}',
      '',
      '/** Value object used for frequent 2D transform updates. */',
      'export interface Transform2D {',
      '  position: [number, number];',
      '  rotation?: number;',
      '  scale?: [number, number];',
      '  zLayer?: number;',
      '  drawOrder?: number;',
      '}',
      '',
      '/** Optional world-space target used by a 3D camera. */',
      'export interface CameraLookAt3D {',
      '  target: [number, number, number];',
      '  up?: [number, number, number];',
      '}',
      ''
    ];

    for (const desc of context.descriptors) {
      lines.push(renderDescriptor(desc));
      lines.push('');
    }

    lines.push(
      '/** Ergonomic helper factories for ViewportRect responsive descriptors. */',
      'export const ViewportRect = {',
      '  full(): ViewportRect {',
      '    return {',
      '      width: { vw: 100 },',
      '      height: { vh: 100 }',
      '    };',
      '  },',
      '  px(x: number, y: number, width: number, height: number): ViewportRect {',
      '    return {',
      '      offsetX: { px: x },',
      '      offsetY: { px: y },',
      '      width: { px: width },',
      '      height: { px: height }',
      '    };',
      '  },',
      '  pip(',
      "    anchorX: AnchorX = 'right',",
      "    anchorY: AnchorY = 'bottom',",
      '    widthVw = 30,',
      '    heightVh = 30,',
      '    marginPx = 20',
      '  ): ViewportRect {',
      '    return {',
      '      anchorX,',
      '      anchorY,',
      '      offsetX: { px: marginPx },',
      '      offsetY: { px: marginPx },',
      '      width: { vw: widthVw },',
      '      height: { vh: heightVh }',
      '    };',
      '  }',
      '};',
      ''
    );

    lines.push('/** Native interface signature exposed by Galfus Engine (Node-API / Bun). */');
    lines.push('export interface GalfusEngine {');

    for (const fn of context.functions) {
      const outParam = fn.params.find((p) => p.out && isNativeStruct(p.type));
      const outStruct =
        outParam && isNativeStruct(outParam.type) ? outParam.type.nativeStruct : undefined;
      const params = fn.params
        .filter((p) => !p.out)
        .map((p) => `${p.name}: ${mapParamTsType(p.type)}`)
        .join(', ');
      const retType = outStruct
        ? outStruct === 'CameraLookAt3D'
          ? 'CameraLookAt3DStateDesc'
          : outStruct
        : mapReturnTsType(fn.returnType, Boolean(fn.returnsParamField));

      lines.push(`  /** ${fn.doc} */`);
      lines.push(`  ${fn.methodName}(${params}): ${retType};`);
    }

    lines.push('  /** Reads the resolved physical size [width, height] of a Multiverse Target. */');
    lines.push('  multiverseGetTargetSize?(targetId: number): [number, number];');
    lines.push('  /** Reads the inner physical size [width, height] of a Platform window. */');
    lines.push('  platformGetWindowSize?(windowId: number): [number, number];');
    lines.push(
      '  /** Reads the world-space bounding box { min: [x,y,z], max: [x,y,z] } of a 3D model. */'
    );
    lines.push(
      '  realm3dGetModelAabb?(realmId: number, modelId: number): { min: [number, number, number]; max: [number, number, number] };'
    );

    lines.push('}', '');
    return lines.join('\n');
  }
}
