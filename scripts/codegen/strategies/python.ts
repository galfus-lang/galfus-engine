import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { type DataType, isBuffer, isJson, isJsonArray, isNativeStruct } from '../spec.ts';

function toSnakeCase(str: string): string {
  return str.replace(/([A-Z])/g, '_$1').toLowerCase();
}

function mapPythonCType(type: DataType, isParam: boolean): string {
  if (isNativeStruct(type)) {
    return `ctypes.POINTER(Galfus${type.nativeStruct})`;
  }
  if (isBuffer(type)) {
    const element =
      type.buffer === 'u8'
        ? 'ctypes.c_uint8'
        : type.buffer === 'u32'
          ? 'ctypes.c_uint32'
          : 'ctypes.c_float';
    return isParam ? `ctypes.POINTER(${element})` : `ctypes.POINTER(${element})`;
  }
  if (typeof type === 'object') {
    return isParam ? 'ctypes.c_char_p' : 'ctypes.c_void_p';
  }
  switch (type) {
    case 'i32':
      return 'ctypes.c_int32';
    case 'u32':
      return 'ctypes.c_uint32';
    case 'u64':
      return 'ctypes.c_uint64';
    case 'f32':
      return 'ctypes.c_float';
    case 'f64':
      return 'ctypes.c_double';
    case 'bool':
      return 'ctypes.c_bool';
    case 'string':
      return isParam ? 'ctypes.c_char_p' : 'ctypes.c_void_p';
    default:
      return 'ctypes.c_void_p';
  }
}

