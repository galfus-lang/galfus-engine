import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { type DataType, isBuffer, isJson, isJsonArray } from '../spec.ts';

function toSnakeCase(str: string): string {
  return str.replace(/([A-Z])/g, '_$1').toLowerCase();
}

function mapPythonCType(type: DataType, isParam: boolean): string {
  if (isBuffer(type)) {
    const element =
      type.buffer === 'u8'
        ? 'ctypes.c_uint8'
        : type.buffer === 'u32'
          ? 'ctypes.c_uint32'
          : 'ctypes.c_float';
    return isParam ? `ctypes.POINTER(${element})` : `ctypes.POINTER(${element})`;
  }
  if (typeof type === 'object') {
    return isParam ? 'ctypes.c_char_p' : 'ctypes.c_void_p';
  }
  switch (type) {
    case 'i32':
      return 'ctypes.c_int32';
    case 'u32':
      return 'ctypes.c_uint32';
    case 'u64':
      return 'ctypes.c_uint64';
    case 'f32':
      return 'ctypes.c_float';
    case 'f64':
      return 'ctypes.c_double';
    case 'bool':
      return 'ctypes.c_bool';
    case 'string':
      return isParam ? 'ctypes.c_char_p' : 'ctypes.c_void_p';
    default:
      return 'ctypes.c_void_p';
  }
}

export class PythonStrategy implements CodegenStrategy {
  readonly id = 'python';
  readonly name = 'Python Wrapper';
  readonly relativeOutputDir = 'sdk/python';
  readonly filename = 'galfus.py';

  generate(context: CodegenContext): string {
    const lines: string[] = [
      '"""Automatically generated by Galfus Engine codegen. Do not edit directly."""',
      'from __future__ import annotations',
      '',
      'import ctypes',
      'import json',
      'import os',
      'import platform',
      'from typing import Any, Dict, List, Optional, Union',
      '',
      'def _load_library() -> ctypes.CDLL:',
      '    system = platform.system()',
      '    if system == "Windows":',
      '        lib_name = "galfus.dll"',
      '    elif system == "Darwin":',
      '        lib_name = "libgalfus_native.dylib"',
      '    else:',
      '        lib_name = "libgalfus_native.so"',
      '',
      '    candidate_paths = [',
      '        lib_name,',
      '        os.path.join(os.path.dirname(__file__), lib_name),',
      '        os.path.join(os.path.dirname(__file__), "../../build/cargo-target/debug", lib_name),',
      '        os.path.join(os.path.dirname(__file__), "../../build/cargo-target/release", lib_name),',
      '    ]',
      '    for path in candidate_paths:',
      '        if os.path.exists(path):',
      '            return ctypes.CDLL(path)',
      '    try:',
      '        return ctypes.CDLL(lib_name)',
      '    except OSError as err:',
      '        raise RuntimeError(f"Could not locate Galfus library ({lib_name}): {err}")',
      '',
      '_lib = _load_library()',
      '',
      '# String deallocator signature',
      '_lib.galfus_string_free.argtypes = [ctypes.c_void_p]',
      '_lib.galfus_string_free.restype = None',
      '',
      'def _consume_string(ptr: Optional[int]) -> str:',
      '    if not ptr:',
      '        return ""',
      '    try:',
      '        return ctypes.string_at(ptr).decode("utf-8")',
      '    finally:',
      '        _lib.galfus_string_free(ptr)',
      '',
      'class GalfusError(Exception):',
      '    """Exception raised when a Galfus engine call fails."""',
      '    pass',
      ''
    ];

    for (const fn of context.functions) {
      const pyFuncName = toSnakeCase(fn.methodName);

      // Ctypes argtypes and restype
      if (fn.params.length > 0) {
        const argtypes = fn.params.map((p) => mapPythonCType(p.type, true)).join(', ');
        lines.push(`_lib.${fn.cName}.argtypes = [${argtypes}]`);
      } else {
        lines.push(`_lib.${fn.cName}.argtypes = []`);
      }

      if (isJson(fn.returnType) || isJsonArray(fn.returnType) || fn.returnType === 'string') {
        lines.push(`_lib.${fn.cName}.restype = ctypes.c_void_p`);
      } else if (fn.returnType === 'i32') {
        lines.push(`_lib.${fn.cName}.restype = ctypes.c_int32`);
      } else if (fn.returnType === 'u32') {
        lines.push(`_lib.${fn.cName}.restype = ctypes.c_uint32`);
      } else if (fn.returnType === 'u64') {
        lines.push(`_lib.${fn.cName}.restype = ctypes.c_uint64`);
      } else if (fn.returnType === 'f32') {
        lines.push(`_lib.${fn.cName}.restype = ctypes.c_float`);
      } else if (fn.returnType === 'f64') {
        lines.push(`_lib.${fn.cName}.restype = ctypes.c_double`);
      } else if (fn.returnType === 'bool') {
        lines.push(`_lib.${fn.cName}.restype = ctypes.c_bool`);
      } else {
        lines.push(`_lib.${fn.cName}.restype = None`);
      }

      lines.push('');

      // Python function signature
      const typedParams: string[] = [];
      for (const p of fn.params) {
        const pName = toSnakeCase(p.name);
        if (isJson(p.type) || isJsonArray(p.type)) {
          typedParams.push(`${pName}: Union[Dict[str, Any], List[Any], str]`);
        } else if (p.type === 'string') {
          typedParams.push(`${pName}: str`);
        } else if (p.type === 'i32' || p.type === 'u32' || p.type === 'u64') {
          typedParams.push(`${pName}: int`);
        } else if (p.type === 'f32' || p.type === 'f64') {
          typedParams.push(`${pName}: float`);
        } else if (p.type === 'bool') {
          typedParams.push(`${pName}: bool`);
        } else {
          typedParams.push(`${pName}: Any`);
        }
      }

      let returnAnnotation = 'None';
      if (isJson(fn.returnType)) {
        returnAnnotation = 'Dict[str, Any]';
      } else if (isJsonArray(fn.returnType)) {
        returnAnnotation = 'List[Any]';
      } else if (fn.returnType === 'string') {
        returnAnnotation = 'str';
      } else if (fn.returnsParamField) {
        returnAnnotation = 'int';
      }

      lines.push(`def ${pyFuncName}(${typedParams.join(', ')}) -> ${returnAnnotation}:`);
      lines.push(`    """${fn.doc}"""`);

      const callArgs: string[] = [];
      for (const p of fn.params) {
        const pName = toSnakeCase(p.name);
        if (isJson(p.type) || isJsonArray(p.type)) {
          lines.push(
            `    _${pName}_raw = ${pName} if isinstance(${pName}, str) else json.dumps(${pName})`
          );
          lines.push(`    _${pName}_bytes = _${pName}_raw.encode("utf-8")`);
          callArgs.push(`_${pName}_bytes`);
        } else if (p.type === 'string') {
          lines.push(`    _${pName}_bytes = ${pName}.encode("utf-8")`);
          callArgs.push(`_${pName}_bytes`);
        } else {
          callArgs.push(pName);
        }
      }

      if (isJson(fn.returnType) || isJsonArray(fn.returnType)) {
        lines.push(`    json_str = _consume_string(_lib.${fn.cName}(${callArgs.join(', ')}))`);
        lines.push(`    if not json_str:`);
        lines.push(`        return ${isJsonArray(fn.returnType) ? '[]' : '{}'}`);
        lines.push(`    return json.loads(json_str)`);
      } else if (fn.returnType === 'string') {
        lines.push(`    return _consume_string(_lib.${fn.cName}(${callArgs.join(', ')}))`);
      } else if (fn.returnType === 'i32') {
        lines.push(`    res = _lib.${fn.cName}(${callArgs.join(', ')})`);
        lines.push(`    if res != 0:`);
        lines.push(`        raise GalfusError(f"${fn.methodName} failed: {get_last_error()}")`);
        if (fn.returnsParamField) {
          const pName = toSnakeCase(fn.returnsParamField.paramName);
          const field = fn.returnsParamField.fieldName;
          lines.push(`    if isinstance(${pName}, dict) and "${field}" in ${pName}:`);
          lines.push(`        return ${pName}["${field}"]`);
          lines.push(`    return 0`);
        }
      } else {
        lines.push(`    return _lib.${fn.cName}(${callArgs.join(', ')})`);
      }

      lines.push('');
    }

    return lines.join('\n');
  }
}
