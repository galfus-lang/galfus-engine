import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { type DataType, isJson, isJsonArray } from '../spec.ts';

function mapFFIType(type: DataType): string {
  if (typeof type === 'object') {
    return 'FFIType.ptr';
  }
  switch (type) {
    case 'i32':
      return 'FFIType.i32';
    case 'u32':
      return 'FFIType.u32';
    case 'u64':
      return 'FFIType.u64';
    case 'f32':
      return 'FFIType.f32';
    case 'f64':
      return 'FFIType.f64';
    case 'bool':
      return 'FFIType.bool';
    case 'string':
      return 'FFIType.ptr';
    case 'void':
      return 'FFIType.void';
    default:
      return 'FFIType.ptr';
  }
}

function mapParamTsType(type: DataType): string {
  if (isJson(type)) {
    if (type.json === 'Transform3DDesc') {
      return `Transform3DDesc | Float32Array | number[] | string`;
    }
    if (type.json === 'Transform2DDesc') {
      return `Transform2DDesc | Float32Array | number[] | string`;
    }
    return `${type.json} | string`;
  }
  if (isJsonArray(type)) {
    return `${type.jsonArray}[] | string`;
  }
  switch (type) {
    case 'bool':
      return 'boolean';
    case 'i32':
    case 'u32':
    case 'u64':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      return 'string';
    case 'void':
      return 'void';
    case 'ptr':
      return 'any';
    default:
      return 'any';
  }
}

function mapReturnTsType(fnReturnType: DataType, hasParamFieldReturn: boolean): string {
  if (hasParamFieldReturn) {
    return 'number';
  }
  if (isJson(fnReturnType)) {
    return fnReturnType.json;
  }
  if (isJsonArray(fnReturnType)) {
    return `${fnReturnType.jsonArray}[]`;
  }
  switch (fnReturnType) {
    case 'bool':
      return 'boolean';
    case 'i32':
      return 'void';
    case 'u32':
    case 'u64':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      return 'string';
    case 'void':
      return 'void';
    default:
      return 'void';
  }
}

export class BunFfiStrategy implements CodegenStrategy {
  readonly id = 'bun_ffi';
  readonly name = 'Bun FFI Wrapper';
  readonly relativeOutputDir = 'sdk/bun';
  readonly filename = 'galfus.ts';

  generate(context: CodegenContext): string {
    const BUILTIN_TS_TYPES = new Set(['number', 'string', 'boolean', 'any', 'void']);
    const importedTypes = new Set<string>(['GalfusEngine']);
    const addType = (t: string) => {
      const clean = t.replace(/\[\]$/, '').trim();
      if (!BUILTIN_TS_TYPES.has(clean)) {
        importedTypes.add(clean);
      }
    };
    for (const fn of context.functions) {
      if (isJson(fn.returnType)) addType(fn.returnType.json);
      if (isJsonArray(fn.returnType)) addType(fn.returnType.jsonArray);
      for (const p of fn.params) {
        if (isJson(p.type)) addType(p.type.json);
        if (isJsonArray(p.type)) addType(p.type.jsonArray);
      }
    }

    importedTypes.delete('ViewportRect');
    const typeImports = Array.from(importedTypes).sort().join(',\n  ');

    const lines: string[] = [
      '/* Automatically generated by Galfus Engine codegen. Do not edit directly. */',
      'import { dlopen, FFIType, CString, ptr as bunPtr } from "bun:ffi";',
      'import { existsSync } from "fs";',
      'import { resolve, dirname } from "path";',
      'import { ViewportRect } from "../typescript/galfus.ts";',
      `import type {`,
      `  ${typeImports}`,
      `} from "../typescript/galfus.ts";`,
      `export type {`,
      `  ${typeImports}`,
      `};`,
      `export { ViewportRect };`,
      '',
      'function locateLibrary(): string {',
      "  const isWindows = process.platform === 'win32';",
      "  const isMac = process.platform === 'darwin';",
      '  const libName = isWindows',
      "    ? 'galfus.dll'",
      '    : isMac',
      "    ? 'libgalfus_native.dylib'",
      "    : 'libgalfus_native.so';",
      '',
      "  const baseDir = typeof import.meta.dir === 'string' ? import.meta.dir : process.cwd();",
      '  const candidates = [',
      '    resolve(baseDir, libName),',
      "    resolve(baseDir, '../../build/cargo-target/debug', libName),",
      "    resolve(baseDir, '../../build/cargo-target/release', libName),",
      "    resolve(baseDir, '../..', libName),",
      '  ];',
      '',
      '  for (const candidate of candidates) {',
      '    if (existsSync(candidate)) {',
      '      return candidate;',
      '    }',
      '  }',
      '  return libName;',
      '}',
      '',
      'export class GalfusError extends Error {',
      '  constructor(message: string) {',
      '    super(message);',
      "    this.name = 'GalfusError';",
      '  }',
      '}',
      '',
      'export class GalfusBun implements GalfusEngine {',
      '  private _lib: any;',
      '',
      '  constructor(customLibPath?: string) {',
      '    const path = customLibPath ?? locateLibrary();',
      '    this._lib = dlopen(path, {',
      '      galfus_string_free: {',
      '        args: [FFIType.ptr],',
      '        returns: FFIType.void,',
      '      },'
    ];

    for (const fn of context.functions) {
      const args = fn.params.map((p) => mapFFIType(p.type)).join(', ');
      const returns = mapFFIType(fn.returnType);
      lines.push(`      ${fn.cName}: {`);
      lines.push(`        args: [${args}],`);
      lines.push(`        returns: ${returns},`);
      lines.push('      },');
    }

    lines.push(
      '    });',
      '  }',
      '',
      '  private consumeString(rawPtr: any): string {',
      "    if (!rawPtr) return '';",
      '    try {',
      '      return new CString(rawPtr).toString();',
      '    } finally {',
      '      this._lib.symbols.galfus_string_free(rawPtr);',
      '    }',
      '  }',
      '',
      '  private toCString(str: string): Uint8Array {',
      "    return Buffer.from(str + '\\0', 'utf-8');",
      '  }',
      '',
      '  private toCJsonOrString(val: any): Uint8Array {',
      "    const str = typeof val === 'string' ? val : JSON.stringify(val);",
      "    return Buffer.from(str + '\\0', 'utf-8');",
      '  }',
      ''
    );

    for (const fn of context.functions) {
      const params = fn.params.map((p) => `${p.name}: ${mapParamTsType(p.type)}`).join(', ');
      const retType = mapReturnTsType(fn.returnType, Boolean(fn.returnsParamField));

      lines.push(`  /** ${fn.doc} */`);
      lines.push(`  ${fn.methodName}(${params}): ${retType} {`);

      if (fn.methodName === 'realm3dSetModelTransform') {
        lines.push(`    if (Array.isArray(transform) || ArrayBuffer.isView(transform)) {`);
        lines.push(
          `      const _arr = ArrayBuffer.isView(transform) ? (transform as Float32Array) : new Float32Array(transform);`
        );
        lines.push(`      this.realm3dSetModelTransformRaw(realmId, modelId, _arr);`);
        lines.push(`      return;`);
        lines.push(`    }`);
      } else if (fn.methodName === 'realm3dSetCameraTransform') {
        lines.push(`    if (Array.isArray(transform) || ArrayBuffer.isView(transform)) {`);
        lines.push(
          `      const _arr = ArrayBuffer.isView(transform) ? (transform as Float32Array) : new Float32Array(transform);`
        );
        lines.push(`      this.realm3dSetCameraTransformRaw(realmId, cameraId, _arr);`);
        lines.push(`      return;`);
        lines.push(`    }`);
      } else if (fn.methodName === 'realm2dSetSpriteTransform') {
        lines.push(`    if (Array.isArray(transform) || ArrayBuffer.isView(transform)) {`);
        lines.push(
          `      const _arr = ArrayBuffer.isView(transform) ? (transform as Float32Array) : new Float32Array(transform);`
        );
        lines.push(`      this.realm2dSetSpriteTransformRaw(realmId, spriteId, _arr);`);
        lines.push(`      return;`);
        lines.push(`    }`);
      } else if (fn.methodName === 'realm2dSetCameraTransform') {
        lines.push(`    if (Array.isArray(transform) || ArrayBuffer.isView(transform)) {`);
        lines.push(
          `      const _arr = ArrayBuffer.isView(transform) ? (transform as Float32Array) : new Float32Array(transform);`
        );
        lines.push(`      this.realm2dSetCameraTransformRaw(realmId, cameraId, _arr);`);
        lines.push(`      return;`);
        lines.push(`    }`);
      }

      const ffiArgs: string[] = [];
      for (const p of fn.params) {
        if (isJson(p.type) || isJsonArray(p.type)) {
          lines.push(`    const _${p.name}_buf = this.toCJsonOrString(${p.name});`);
          ffiArgs.push(`bunPtr(_${p.name}_buf)`);
        } else if (p.type === 'string') {
          lines.push(`    const _${p.name}_buf = this.toCString(${p.name});`);
          ffiArgs.push(`bunPtr(_${p.name}_buf)`);
        } else if (p.type === 'ptr') {
          lines.push(
            `    const _${p.name}_ptr = ArrayBuffer.isView(${p.name}) ? bunPtr(${p.name} as any) : ${p.name};`
          );
          ffiArgs.push(`_${p.name}_ptr`);
        } else {
          ffiArgs.push(p.name);
        }
      }

      const callExpr = `this._lib.symbols.${fn.cName}(${ffiArgs.join(', ')})`;

      if (isJson(fn.returnType) || isJsonArray(fn.returnType)) {
        lines.push(`    const rawPtr = ${callExpr};`);
        lines.push(`    const jsonStr = this.consumeString(rawPtr);`);
        lines.push(`    if (!jsonStr) {`);
        lines.push(`      return ${isJsonArray(fn.returnType) ? '[]' : '{}'} as ${retType};`);
        lines.push(`    }`);
        lines.push(`    return JSON.parse(jsonStr) as ${retType};`);
      } else if (fn.returnType === 'string') {
        lines.push(`    const rawPtr = ${callExpr};`);
        lines.push(`    return this.consumeString(rawPtr);`);
      } else if (fn.returnType === 'i32') {
        lines.push(`    const res = ${callExpr};`);
        lines.push(`    if (res !== 0) {`);
        lines.push(
          `      throw new GalfusError(\`${fn.methodName} failed: \${this.getLastError()}\`);`
        );
        lines.push(`    }`);
        if (fn.returnsParamField) {
          const pName = fn.returnsParamField.paramName;
          const field = fn.returnsParamField.fieldName;
          lines.push(
            `    if (typeof ${pName} === 'object' && ${pName} !== null && '${field}' in ${pName}) {`
          );
          lines.push(`      return (${pName} as any).${field};`);
          lines.push(`    }`);
          lines.push(`    if (typeof ${pName} === 'string') {`);
          lines.push(`      return JSON.parse(${pName}).${field};`);
          lines.push(`    }`);
          lines.push(`    return 0;`);
        }
      } else {
        lines.push(`    return ${callExpr};`);
      }

      lines.push('  }');
      lines.push('');
    }

    lines.push(
      '  /** Reads the resolved physical size [width, height] of a Multiverse Target. */',
      '  multiverseGetTargetSize(targetId: number): [number, number] {',
      '    const wBuf = new Uint32Array(1);',
      '    const hBuf = new Uint32Array(1);',
      '    this.multiverseGetTargetSizeRaw(targetId, wBuf, hBuf);',
      '    return [wBuf[0]!, hBuf[0]!];',
      '  }',
      '',
      '  /** Reads the inner physical size [width, height] of a Platform window. */',
      '  platformGetWindowSize(windowId: number): [number, number] {',
      '    const wBuf = new Uint32Array(1);',
      '    const hBuf = new Uint32Array(1);',
      '    this.platformGetWindowSizeRaw(windowId, wBuf, hBuf);',
      '    return [wBuf[0]!, hBuf[0]!];',
      '  }',
      '',
      '  /** Reads the 10-float transform array [px, py, pz, rx, ry, rz, rw, sx, sy, sz] of a 3D model. */',
      '  realm3dGetModelTransform(realmId: number, modelId: number): Float32Array {',
      '    const buf = new Float32Array(10);',
      '    this.realm3dGetModelTransformRaw(realmId, modelId, buf);',
      '    return buf;',
      '  }',
      '',
      '  /** Reads the 10-float transform array [px, py, pz, rx, ry, rz, rw, sx, sy, sz] of a 3D camera. */',
      '  realm3dGetCameraTransform(realmId: number, cameraId: number): Float32Array {',
      '    const buf = new Float32Array(10);',
      '    this.realm3dGetCameraTransformRaw(realmId, cameraId, buf);',
      '    return buf;',
      '  }',
      '',
      '  /** Reads the world-space bounding box { min: [x,y,z], max: [x,y,z] } of a 3D model. */',
      '  realm3dGetModelAabb(realmId: number, modelId: number): { min: [number, number, number]; max: [number, number, number] } {',
      '    const minBuf = new Float32Array(3);',
      '    const maxBuf = new Float32Array(3);',
      '    this.realm3dGetModelAabbRaw(realmId, modelId, minBuf, maxBuf);',
      '    return {',
      '      min: [minBuf[0]!, minBuf[1]!, minBuf[2]!],',
      '      max: [maxBuf[0]!, maxBuf[1]!, maxBuf[2]!]',
      '    };',
      '  }',
      '',
      '  /** Reads the 6-float transform array [px, py, rot, sx, sy, zLayer] of a 2D sprite. */',
      '  realm2dGetSpriteTransform(realmId: number, spriteId: number): Float32Array {',
      '    const buf = new Float32Array(6);',
      '    this.realm2dGetSpriteTransformRaw(realmId, spriteId, buf);',
      '    return buf;',
      '  }',
      '',
      '  /** Reads the 6-float transform array [px, py, rot, sx, sy, zLayer] of a 2D camera. */',
      '  realm2dGetCameraTransform(realmId: number, cameraId: number): Float32Array {',
      '    const buf = new Float32Array(6);',
      '    this.realm2dGetCameraTransformRaw(realmId, cameraId, buf);',
      '    return buf;',
      '  }',
      ''
    );

    lines.push('}', '', 'export const galfus = new GalfusBun();', '');
    return lines.join('\n');
  }
}
