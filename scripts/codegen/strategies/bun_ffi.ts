import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { type DataType, isJson, isJsonArray } from '../spec.ts';

function mapFFIType(type: DataType): string {
  if (typeof type === 'object') {
    return 'FFIType.ptr';
  }
  switch (type) {
    case 'i32':
      return 'FFIType.i32';
    case 'u32':
      return 'FFIType.u32';
    case 'u64':
      return 'FFIType.u64';
    case 'f32':
      return 'FFIType.f32';
    case 'f64':
      return 'FFIType.f64';
    case 'bool':
      return 'FFIType.bool';
    case 'string':
      return 'FFIType.ptr';
    case 'void':
      return 'FFIType.void';
    default:
      return 'FFIType.ptr';
  }
}

function mapParamTsType(type: DataType): string {
  if (isJson(type)) {
    return `${type.json} | string`;
  }
  if (isJsonArray(type)) {
    return `${type.jsonArray}[] | string`;
  }
  switch (type) {
    case 'bool':
      return 'boolean';
    case 'i32':
    case 'u32':
    case 'u64':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      return 'string';
    case 'void':
      return 'void';
    default:
      return 'any';
  }
}

function mapReturnTsType(fnReturnType: DataType, hasParamFieldReturn: boolean): string {
  if (hasParamFieldReturn) {
    return 'number';
  }
  if (isJson(fnReturnType)) {
    return fnReturnType.json;
  }
  if (isJsonArray(fnReturnType)) {
    return `${fnReturnType.jsonArray}[]`;
  }
  switch (fnReturnType) {
    case 'bool':
      return 'boolean';
    case 'i32':
      return 'void';
    case 'u32':
    case 'u64':
    case 'f32':
    case 'f64':
      return 'number';
    case 'string':
      return 'string';
    case 'void':
      return 'void';
    default:
      return 'void';
  }
}

export class BunFfiStrategy implements CodegenStrategy {
  readonly id = 'bun_ffi';
  readonly name = 'Bun FFI Wrapper';
  readonly relativeOutputDir = 'sdk/bun';
  readonly filename = 'galfus.ts';

  generate(context: CodegenContext): string {
    const BUILTIN_TS_TYPES = new Set(['number', 'string', 'boolean', 'any', 'void']);
    const importedTypes = new Set<string>(['GalfusEngine']);
    const addType = (t: string) => {
      const clean = t.replace(/\[\]$/, '').trim();
      if (!BUILTIN_TS_TYPES.has(clean)) {
        importedTypes.add(clean);
      }
    };
    for (const fn of context.functions) {
      if (isJson(fn.returnType)) addType(fn.returnType.json);
      if (isJsonArray(fn.returnType)) addType(fn.returnType.jsonArray);
      for (const p of fn.params) {
        if (isJson(p.type)) addType(p.type.json);
        if (isJsonArray(p.type)) addType(p.type.jsonArray);
      }
    }

    const typeImports = Array.from(importedTypes).sort().join(',\n  ');

    const lines: string[] = [
      '/* Automatically generated by Galfus Engine codegen. Do not edit directly. */',
      'import { dlopen, FFIType, CString, ptr } from "bun:ffi";',
      'import { existsSync } from "fs";',
      'import { resolve, dirname } from "path";',
      `import type {`,
      `  ${typeImports}`,
      `} from "../typescript/galfus.ts";`,
      '',
      'function locateLibrary(): string {',
      "  const isWindows = process.platform === 'win32';",
      "  const isMac = process.platform === 'darwin';",
      '  const libName = isWindows',
      "    ? 'galfus.dll'",
      '    : isMac',
      "    ? 'libgalfus_native.dylib'",
      "    : 'libgalfus_native.so';",
      '',
      "  const baseDir = typeof import.meta.dir === 'string' ? import.meta.dir : process.cwd();",
      '  const candidates = [',
      '    resolve(baseDir, libName),',
      "    resolve(baseDir, '../../build/cargo-target/debug', libName),",
      "    resolve(baseDir, '../../build/cargo-target/release', libName),",
      "    resolve(baseDir, '../..', libName),",
      '  ];',
      '',
      '  for (const candidate of candidates) {',
      '    if (existsSync(candidate)) {',
      '      return candidate;',
      '    }',
      '  }',
      '  return libName;',
      '}',
      '',
      'export class GalfusError extends Error {',
      '  constructor(message: string) {',
      '    super(message);',
      "    this.name = 'GalfusError';",
      '  }',
      '}',
      '',
      'export class GalfusBun implements GalfusEngine {',
      '  private _lib: any;',
      '',
      '  constructor(customLibPath?: string) {',
      '    const path = customLibPath ?? locateLibrary();',
      '    this._lib = dlopen(path, {',
      '      galfus_string_free: {',
      '        args: [FFIType.ptr],',
      '        returns: FFIType.void,',
      '      },'
    ];

    for (const fn of context.functions) {
      const args = fn.params.map((p) => mapFFIType(p.type)).join(', ');
      const returns = mapFFIType(fn.returnType);
      lines.push(`      ${fn.cName}: {`);
      lines.push(`        args: [${args}],`);
      lines.push(`        returns: ${returns},`);
      lines.push('      },');
    }

    lines.push(
      '    });',
      '  }',
      '',
      '  private consumeString(rawPtr: any): string {',
      "    if (!rawPtr) return '';",
      '    try {',
      '      return new CString(rawPtr).toString();',
      '    } finally {',
      '      this._lib.symbols.galfus_string_free(rawPtr);',
      '    }',
      '  }',
      '',
      '  private toCString(str: string): Uint8Array {',
      "    return Buffer.from(str + '\\0', 'utf-8');",
      '  }',
      '',
      '  private toCJsonOrString(val: any): Uint8Array {',
      "    const str = typeof val === 'string' ? val : JSON.stringify(val);",
      "    return Buffer.from(str + '\\0', 'utf-8');",
      '  }',
      ''
    );

    for (const fn of context.functions) {
      const params = fn.params.map((p) => `${p.name}: ${mapParamTsType(p.type)}`).join(', ');
      const retType = mapReturnTsType(fn.returnType, Boolean(fn.returnsParamField));

      lines.push(`  /** ${fn.doc} */`);
      lines.push(`  ${fn.methodName}(${params}): ${retType} {`);

      const ffiArgs: string[] = [];
      for (const p of fn.params) {
        if (isJson(p.type) || isJsonArray(p.type)) {
          lines.push(`    const _${p.name}_buf = this.toCJsonOrString(${p.name});`);
          ffiArgs.push(`ptr(_${p.name}_buf)`);
        } else if (p.type === 'string') {
          lines.push(`    const _${p.name}_buf = this.toCString(${p.name});`);
          ffiArgs.push(`ptr(_${p.name}_buf)`);
        } else {
          ffiArgs.push(p.name);
        }
      }

      const callExpr = `this._lib.symbols.${fn.cName}(${ffiArgs.join(', ')})`;

      if (isJson(fn.returnType) || isJsonArray(fn.returnType)) {
        lines.push(`    const rawPtr = ${callExpr};`);
        lines.push(`    const jsonStr = this.consumeString(rawPtr);`);
        lines.push(`    if (!jsonStr) {`);
        lines.push(`      return ${isJsonArray(fn.returnType) ? '[]' : '{}'} as ${retType};`);
        lines.push(`    }`);
        lines.push(`    return JSON.parse(jsonStr) as ${retType};`);
      } else if (fn.returnType === 'string') {
        lines.push(`    const rawPtr = ${callExpr};`);
        lines.push(`    return this.consumeString(rawPtr);`);
      } else if (fn.returnType === 'i32') {
        lines.push(`    const res = ${callExpr};`);
        lines.push(`    if (res !== 0) {`);
        lines.push(
          `      throw new GalfusError(\`${fn.methodName} failed: \${this.getLastError()}\`);`
        );
        lines.push(`    }`);
        if (fn.returnsParamField) {
          const pName = fn.returnsParamField.paramName;
          const field = fn.returnsParamField.fieldName;
          lines.push(
            `    if (typeof ${pName} === 'object' && ${pName} !== null && '${field}' in ${pName}) {`
          );
          lines.push(`      return (${pName} as any).${field};`);
          lines.push(`    }`);
          lines.push(`    if (typeof ${pName} === 'string') {`);
          lines.push(`      return JSON.parse(${pName}).${field};`);
          lines.push(`    }`);
          lines.push(`    return 0;`);
        }
      } else {
        lines.push(`    return ${callExpr};`);
      }

      lines.push('  }');
      lines.push('');
    }

    lines.push('}', '', 'export const galfus = new GalfusBun();', '');
    return lines.join('\n');
  }
}
