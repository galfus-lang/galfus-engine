import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { collectEngineTypes, engineMethodLines } from './ts_engine_methods.ts';

/** Engine methods that return a Promise in the browser because GPU setup cannot block. */
const ASYNC_METHODS: ReadonlySet<string> = new Set(['multiverseAttachWindow']);
const AUDIO_METHODS: ReadonlySet<string> = new Set([
  'audioLoadSound',
  'audioPlaySound',
  'audioPlaySoundSpatial',
  'audioUpdateSoundSpatial',
  'audioPauseSound',
  'audioResumeSound',
  'audioStopSound',
  'audioSetVolume',
  'audioSetPanning',
  'audioUnloadSound'
]);

export class BrowserWasmStrategy implements CodegenStrategy {
  readonly id = 'browser_wasm';
  readonly name = 'Browser WASM SDK';
  readonly relativeOutputDir = 'sdk/browser';
  readonly filename = 'galfus.ts';

  generate(context: CodegenContext): string {
    const typeSet = collectEngineTypes(context);
    for (const name of [
      'GamepadInfo',
      'PlatformCapabilities',
      'PlatformEvent',
      'SpatialAudioConfig',
      'SpatialTransform',
      'WindowConfig'
    ]) {
      typeSet.add(name);
    }
    const typeExports = Array.from(typeSet).sort();
    const lines: string[] = [
      '/* Automatically generated by Galfus Engine codegen. Do not edit directly. */',
      '/* Browser/WASM public API contract for the wasm-bindgen GalfusBrowser module. */',
      '',
      `import type { ${typeExports.join(', ')} } from '../typescript/galfus.ts';`,
      `export type { ${typeExports.join(', ')} } from '../typescript/galfus.ts';`,
      "import { WasmAudio } from './audio.ts';",
      ''
    ];

    lines.push(
      '/** Shape of the JavaScript module generated by wasm-bindgen with --target web. */',
      'export interface GalfusBrowserWasmModule {',
      '  default(input?: unknown): Promise<unknown>;',
      '  [exportName: string]: unknown;',
      '}',
      '',
      '/** Error raised when the loaded WASM module lacks an engine method. */',
      'export class GalfusError extends Error {',
      '  constructor(message: string) {',
      '    super(message);',
      "    this.name = 'GalfusError';",
      '  }',
      '}',
      '',
      '/** Full engine API (platform, multiverse, realms, animation) backed by the WASM module. */',
      'export class GalfusBrowser implements GalfusEngine {',
      '  private _addon: any;',
      '  private _audio: WasmAudio;',
      '',
      '  constructor(module: unknown) {',
      '    this._addon = module;',
      '    this._audio = new WasmAudio();',
      '  }',
      '',
      '  /** Browser/WASM methods report failures by throwing JavaScript errors. */',
      '  getLastError(): string {',
      "    return '';",
      '  }',
      '',
      '  /** Unlocks Web Audio after a user gesture. */',
      '  enableAudio(): Promise<void> {',
      '    return this._audio.enable();',
      '  }',
      '',
      '  /** Loads raw audio data into the browser Web Audio backend. */',
      '  audioLoadSound(soundId: number, data: any, _dataLen: number): void {',
      '    this._audio.load(soundId, data);',
      '  }',
      '',
      '  /** Plays a loaded sound through Web Audio. */',
      '  audioPlaySound(soundId: number, volume: number, panning: number, speed: number, looping: boolean): number {',
      '    return this._audio.play(soundId, volume, panning, speed, looping);',
      '  }',
      '',
      '  /** Plays a loaded sound with browser spatial attenuation and panning. */',
      '  audioPlaySoundSpatial(soundId: number, spatial: SpatialAudio): number {',
      '    return this._audio.playSpatial(soundId, spatial);',
      '  }',
      '',
      '  /** Updates a browser spatial voice. */',
      '  audioUpdateSoundSpatial(voiceId: number, spatial: SpatialAudio): void {',
      '    this._audio.updateSpatial(voiceId, spatial);',
      '  }',
      '',
      '  /** Pauses a browser voice. */',
      '  audioPauseSound(voiceId: number): void { this._audio.pause(voiceId); }',
      '  /** Resumes a browser voice. */',
      '  audioResumeSound(voiceId: number): void { this._audio.resume(voiceId); }',
      '  /** Stops a browser voice. */',
      '  audioStopSound(voiceId: number): void { this._audio.stop(voiceId); }',
      '  /** Updates a browser voice volume. */',
      '  audioSetVolume(voiceId: number, volume: number): void { this._audio.setVolume(voiceId, volume); }',
      '  /** Updates a browser voice panning. */',
      '  audioSetPanning(voiceId: number, panning: number): void { this._audio.setPanning(voiceId, panning); }',
      '  /** Unloads a browser sound and stops its voices. */',
      '  audioUnloadSound(soundId: number): void { this._audio.unload(soundId); }',
      ''
    );
    lines.push(...engineMethodLines(context, 'WASM', ASYNC_METHODS, AUDIO_METHODS));
    lines.push(
      '',
      '  /** Reads the inner physical size [width, height] of a Platform window. */',
      '  windowGetSize(windowId: number): [number, number] {',
      '    return this._addon.windowGetSize(windowId);',
      '  }',
      '',
      '  /** Reads the inner physical size [width, height] of a Platform window (alias for windowGetSize). */',
      '  platformGetWindowSize(windowId: number): [number, number] {',
      '    return this.windowGetSize(windowId);',
      '  }',
      '}',
      '',
      '/** Initializes the WASM module and returns the full browser engine API. */',
      'export async function initializeGalfusBrowser(',
      '  module: GalfusBrowserWasmModule',
      '): Promise<GalfusBrowser> {',
      '  await module.default();',
      '  return new GalfusBrowser(module);',
      '}',
      ''
    );

    return lines.join('\n');
  }
}
