import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import { type DataType, isBuffer, isJson, isJsonArray, type ParamSpec } from '../spec.ts';

function toSnakeCase(str: string): string {
  return str.replace(/([A-Z])/g, '_$1').toLowerCase();
}

function mapLuaCParam(p: ParamSpec): string {
  const pName = toSnakeCase(p.name);
  if (isBuffer(p.type)) {
    const element =
      p.type.buffer === 'u8' ? 'uint8_t' : p.type.buffer === 'u32' ? 'uint32_t' : 'float';
    return `const ${element}* ${pName}`;
  }
  if (typeof p.type === 'object') {
    return `const char* ${pName}`;
  }
  switch (p.type) {
    case 'i32':
      return `int32_t ${pName}`;
    case 'u32':
      return `uint32_t ${pName}`;
    case 'u64':
      return `uint64_t ${pName}`;
    case 'f32':
      return `float ${pName}`;
    case 'f64':
      return `double ${pName}`;
    case 'bool':
      return `bool ${pName}`;
    case 'string':
      return `const char* ${pName}`;
    default:
      return `void* ${pName}`;
  }
}

function mapLuaCReturn(type: DataType): string {
  if (typeof type === 'object') {
    return 'char*';
  }
  switch (type) {
    case 'void':
      return 'void';
    case 'bool':
      return 'bool';
    case 'i32':
      return 'int32_t';
    case 'u32':
      return 'uint32_t';
    case 'u64':
      return 'uint64_t';
    case 'f32':
      return 'float';
    case 'f64':
      return 'double';
    case 'string':
      return 'char*';
    default:
      return 'void*';
  }
}

export class LuaStrategy implements CodegenStrategy {
  readonly id = 'lua';
  readonly name = 'LuaJIT Wrapper';
  readonly relativeOutputDir = 'sdk/lua';
  readonly filename = 'galfus.lua';

  generate(context: CodegenContext): string {
    const lines: string[] = [
      '-- Automatically generated by Galfus Engine codegen. Do not edit directly.',
      'local ffi = require("ffi")',
      '',
      'ffi.cdef[[',
      '    void galfus_string_free(char* ptr);'
    ];

    for (const fn of context.functions) {
      const params = fn.params.length === 0 ? 'void' : fn.params.map(mapLuaCParam).join(', ');
      const ret = mapLuaCReturn(fn.returnType);
      lines.push(`    ${ret} ${fn.cName}(${params});`);
    }

    lines.push(
      ']]',
      '',
      'local function find_library()',
      '    local candidates = {',
      '        "libgalfus_native.so",',
      '        "./libgalfus_native.so",',
      '        "../../build/cargo-target/debug/libgalfus_native.so",',
      '        "../../build/cargo-target/release/libgalfus_native.so",',
      '        "build/cargo-target/debug/libgalfus_native.so",',
      '        "galfus.dll",',
      '        "libgalfus_native.dylib"',
      '    }',
      '    for _, name in ipairs(candidates) do',
      '        local ok, lib = pcall(ffi.load, name)',
      '        if ok then return lib end',
      '    end',
      '    return ffi.load("libgalfus_native.so")',
      'end',
      '',
      'local clib = find_library()',
      'local M = {}',
      '',
      'local function consume_string(c_str)',
      '    if c_str == nil then return nil end',
      '    local str = ffi.string(c_str)',
      '    clib.galfus_string_free(c_str)',
      '    return str',
      'end',
      ''
    );

    for (const fn of context.functions) {
      const luaFuncName = toSnakeCase(fn.methodName);
      const paramNames = fn.params.map((p) => toSnakeCase(p.name)).join(', ');

      lines.push(`--- ${fn.doc}`);
      lines.push(`function M.${luaFuncName}(${paramNames})`);

      const callArgs = fn.params.map((p) => toSnakeCase(p.name)).join(', ');

      if (isJson(fn.returnType) || isJsonArray(fn.returnType) || fn.returnType === 'string') {
        lines.push(`    return consume_string(clib.${fn.cName}(${callArgs}))`);
      } else if (fn.returnType === 'i32') {
        lines.push(`    local res = clib.${fn.cName}(${callArgs})`);
        lines.push(`    if res ~= 0 then`);
        lines.push(
          `        error("${fn.methodName} failed: " .. (M.get_last_error() or "unknown"))`
        );
        lines.push(`    end`);
        if (fn.returnsParamField) {
          lines.push(`    return 0`);
        }
      } else {
        lines.push(`    return clib.${fn.cName}(${callArgs})`);
      }

      lines.push('end');
      lines.push('');
    }

    lines.push('return M');
    lines.push('');

    return lines.join('\n');
  }
}
