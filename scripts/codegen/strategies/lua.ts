import type { CodegenContext, CodegenStrategy } from './strategy.ts';
import {
  type DataType,
  isBuffer,
  isJson,
  isJsonArray,
  isNativeStruct,
  type ParamSpec
} from '../spec.ts';

function toSnakeCase(str: string): string {
  return str.replace(/([A-Z])/g, '_$1').toLowerCase();
}

function mapLuaCParam(p: ParamSpec): string {
  const pName = toSnakeCase(p.name);
  if (isNativeStruct(p.type)) {
    return `${p.out ? '' : 'const '}Galfus${p.type.nativeStruct}* ${pName}`;
  }
  if (isBuffer(p.type)) {
    const element =
      p.type.buffer === 'u8' ? 'uint8_t' : p.type.buffer === 'u32' ? 'uint32_t' : 'float';
    return `const ${element}* ${pName}`;
  }
  if (typeof p.type === 'object') {
    return `const char* ${pName}`;
  }
  switch (p.type) {
    case 'i32':
      return `int32_t ${pName}`;
    case 'u32':
      return `uint32_t ${pName}`;
    case 'u64':
      return `uint64_t ${pName}`;
    case 'f32':
      return `float ${pName}`;
    case 'f64':
      return `double ${pName}`;
    case 'bool':
      return `bool ${pName}`;
    case 'string':
      return `const char* ${pName}`;
    default:
      return `void* ${pName}`;
  }
}

function mapLuaCReturn(type: DataType): string {
  if (typeof type === 'object') {
    return 'char*';
  }
  switch (type) {
    case 'void':
      return 'void';
    case 'bool':
      return 'bool';
    case 'i32':
      return 'int32_t';
    case 'u32':
      return 'uint32_t';
    case 'u64':
      return 'uint64_t';
    case 'f32':
      return 'float';
    case 'f64':
      return 'double';
    case 'string':
      return 'char*';
    default:
      return 'void*';
  }
}

export class LuaStrategy implements CodegenStrategy {
  readonly id = 'lua';
  readonly name = 'LuaJIT Wrapper';
  readonly relativeOutputDir = 'sdk/lua';
  readonly filename = 'galfus.lua';

  generate(context: CodegenContext): string {
    const lines: string[] = [
      '-- Automatically generated by Galfus Engine codegen. Do not edit directly.',
      'local ffi = require("ffi")',
      '',
      'ffi.cdef[[',
      '    typedef struct { float position_x, position_y, position_z, rotation_x, rotation_y, rotation_z, rotation_w, scale_x, scale_y, scale_z; } GalfusTransform3D;',
      '    typedef struct { float position_x, position_y, rotation, scale_x, scale_y; int32_t z_layer, draw_order; } GalfusTransform2D;',
      '    typedef struct { uint32_t enabled; float target_x, target_y, target_z, up_x, up_y, up_z; } GalfusCameraLookAt3D;',
      '    typedef struct { float emitter_x, emitter_y, emitter_z, emitter_rotation_x, emitter_rotation_y, emitter_rotation_z, emitter_rotation_w, listener_x, listener_y, listener_z, listener_rotation_x, listener_rotation_y, listener_rotation_z, listener_rotation_w, volume, min_distance, max_distance, rolloff, speed; uint32_t looping; } GalfusSpatialAudio;',
      '    typedef struct { uint16_t kind, event_type; uint32_t flags, window_id, subject_id; uint64_t id; float values[5]; uint32_t text0_offset, text0_length, text1_offset, text1_length, text2_offset, text2_length; } GalfusPlatformEvent;',
      '    typedef struct { uint64_t batch_id; const GalfusPlatformEvent* events; uint32_t event_count; const uint8_t* text_data; uint32_t text_length; } GalfusEventBatch;',
      '    void galfus_string_free(char* ptr);'
    ];

    for (const fn of context.functions) {
      const params = fn.params.length === 0 ? 'void' : fn.params.map(mapLuaCParam).join(', ');
      const ret = mapLuaCReturn(fn.returnType);
      lines.push(`    ${ret} ${fn.cName}(${params});`);
    }

    lines.push(
      ']]',
      '',
      'local function find_library()',
      '    local source = debug.getinfo(1, "S").source',
      '    local base_dir = source:sub(1, 1) == "@" and source:sub(2):match("(.*/)") or nil',
      '    base_dir = base_dir or "./"',
      '    local candidates = {',
      '        base_dir .. "../../lib/libgalfus_native.so",',
      '        base_dir .. "../../lib/libgalfus_native.dylib",',
      '        base_dir .. "../../lib/galfus_native.dll",',
      '        "libgalfus_native.so",',
      '        "./libgalfus_native.so",',
      '        "../../build/cargo-target/debug/libgalfus_native.so",',
      '        "../../build/cargo-target/release/libgalfus_native.so",',
      '        "build/cargo-target/debug/libgalfus_native.so",',
      '        "galfus_native.dll",',
      '        "libgalfus_native.dylib"',
      '    }',
      '    for _, name in ipairs(candidates) do',
      '        local ok, lib = pcall(ffi.load, name)',
      '        if ok then return lib end',
      '    end',
      '    return ffi.load("libgalfus_native.so")',
      'end',
      '',
      'local clib = find_library()',
      'local M = {}',
      '',
      'local function consume_string(c_str)',
      '    if c_str == nil then return nil end',
      '    local str = ffi.string(c_str)',
      '    clib.galfus_string_free(c_str)',
      '    return str',
      'end',
      '',
      'local function encode_transform_3d(value)',
      '    local position, rotation, scale = value.position or {0, 0, 0}, value.rotation or {0, 0, 0, 1}, value.scale or {1, 1, 1}',
      '    return ffi.new("GalfusTransform3D", { position_x = position[1], position_y = position[2], position_z = position[3], rotation_x = rotation[1], rotation_y = rotation[2], rotation_z = rotation[3], rotation_w = rotation[4], scale_x = scale[1], scale_y = scale[2], scale_z = scale[3] })',
      'end',
      '',
      'local function decode_transform_3d(value)',
      '    return { position = {value.position_x, value.position_y, value.position_z}, rotation = {value.rotation_x, value.rotation_y, value.rotation_z, value.rotation_w}, scale = {value.scale_x, value.scale_y, value.scale_z} }',
      'end',
      '',
      'local function encode_transform_2d(value)',
      '    local position, scale = value.position or {0, 0}, value.scale or {1, 1}',
      '    return ffi.new("GalfusTransform2D", { position_x = position[1], position_y = position[2], rotation = value.rotation or 0, scale_x = scale[1], scale_y = scale[2], z_layer = value.zLayer or 0, draw_order = value.drawOrder or 0 })',
      'end',
      '',
      'local function decode_transform_2d(value)',
      '    return { position = {value.position_x, value.position_y}, rotation = value.rotation, scale = {value.scale_x, value.scale_y}, zLayer = value.z_layer, drawOrder = value.draw_order }',
      'end',
      '',
      'local function encode_camera_look_at_3d(value)',
      '    local up = value.up or {0, 1, 0}',
      '    return ffi.new("GalfusCameraLookAt3D", { enabled = 1, target_x = value.target[1], target_y = value.target[2], target_z = value.target[3], up_x = up[1], up_y = up[2], up_z = up[3] })',
      'end',
      '',
      'local function decode_camera_look_at_3d(value)',
      '    if value.enabled == 0 then return { enabled = false } end',
      '    return { enabled = true, target = {value.target_x, value.target_y, value.target_z}, up = {value.up_x, value.up_y, value.up_z} }',
      'end',
      '',
      'local function encode_spatial_audio(value)',
      '    local emitter, listener, config = value.emitter, value.listener, value.config',
      '    local er, lr = emitter.rotation or {0, 0, 0, 1}, listener.rotation or {0, 0, 0, 1}',
      '    return ffi.new("GalfusSpatialAudio", { emitter_x = emitter.position[1], emitter_y = emitter.position[2], emitter_z = emitter.position[3], emitter_rotation_x = er[1], emitter_rotation_y = er[2], emitter_rotation_z = er[3], emitter_rotation_w = er[4], listener_x = listener.position[1], listener_y = listener.position[2], listener_z = listener.position[3], listener_rotation_x = lr[1], listener_rotation_y = lr[2], listener_rotation_z = lr[3], listener_rotation_w = lr[4], volume = config.volume or 1, min_distance = config.minDistance or 1, max_distance = config.maxDistance or 100, rolloff = config.rolloff or 1, speed = config.speed or 1, looping = config.looping and 1 or 0 })',
      'end',
      '',
      'local function event_enum(value)',
      '    local other = value:match("^Other%((%d+)%)$")',
      '    if other then return { other = tonumber(other) } end',
      '    return value:sub(1, 1):lower() .. value:sub(2)',
      'end',
      '',
      'local function decode_event_batch(batch)',
      '    local function event_text(offset, length)',
      '        if length == 0 then return "" end',
      '        return ffi.string(batch.text_data + offset, length)',
      '    end',
      '    local ok, events_or_error = pcall(function()',
      '        local events = {}',
      '        for index = 0, tonumber(batch.event_count) - 1 do',
      '            local event = batch.events[index]',
      '            local flags, values = tonumber(event.flags), event.values',
      '            local text0 = event_text(event.text0_offset, event.text0_length)',
      '            local text1 = event_text(event.text1_offset, event.text1_length)',
      '            local text2 = event_text(event.text2_offset, event.text2_length)',
      '            local modifiers = { shift = bit.band(flags, 2) ~= 0, ctrl = bit.band(flags, 4) ~= 0, alt = bit.band(flags, 8) ~= 0, superKey = bit.band(flags, 16) ~= 0 }',
      '            local value',
      '            if event.kind == 1 then',
      '                local names = { "resized", "moved", "closeRequested", "focusChanged", "occluded", "scaleFactorChanged", "redrawRequested" }',
      '                value = { kind = "window", type = names[event.event_type], windowId = event.window_id }',
      '                if event.event_type == 1 then value.width, value.height, value.scaleFactor = values[0], values[1], values[2] end',
      '                if event.event_type == 2 then value.x, value.y = values[0], values[1] end',
      '                if event.event_type == 4 then value.focused = bit.band(flags, 1) ~= 0 end',
      '                if event.event_type == 5 then value.occluded = bit.band(flags, 1) ~= 0 end',
      '                if event.event_type == 6 then value.scaleFactor = values[0] end',
      '            elseif event.kind == 2 then',
      '                local names = { "move", "button", "enter", "leave", "cancel", "scroll" }',
      '                value = { kind = "pointer", type = names[event.event_type], windowId = event.window_id, pointerId = event.id, pointerType = ({ "mouse", "touch", "pen" })[event.subject_id], position = { values[0], values[1] } }',
      '                if event.event_type == 1 then value.delta, value.pressure = { values[2], values[3] }, values[4] end',
      '                if event.event_type == 2 then value.button, value.state, value.pressure = event_enum(text0), bit.band(flags, 1) ~= 0 and "pressed" or "released", values[2] end',
      '                if event.event_type == 6 then value.delta = { [bit.band(flags, 64) ~= 0 and "pixels" or "lines"] = { values[2], values[3] } } end',
      '            elseif event.kind == 3 then',
      '                value = { kind = "keyboard", type = event.event_type == 1 and "input" or "modifiersChanged", windowId = event.window_id, modifiers = modifiers }',
      '                if event.event_type == 1 then value.physicalKey, value.logicalKey, value.state = event_enum(text0), bit.band(flags, 128) ~= 0 and { named = event_enum(text1) } or text1, bit.band(flags, 1) ~= 0 and "pressed" or "released"; value["repeat"] = bit.band(flags, 32) ~= 0 end',
      '                if bit.band(flags, 256) ~= 0 then value.text = text2 end',
      '            else',
      '                local names = { "connected", "disconnected", "button", "axis" }',
      '                value = { kind = "gamepad", type = names[event.event_type], gamepadId = event.subject_id }',
      '                if event.event_type == 1 then value.name = text0 end',
      '                if event.event_type == 3 then value.button, value.state = event_enum(text0), bit.band(flags, 1) ~= 0 and "pressed" or "released" end',
      '                if event.event_type == 4 then value.axis, value.value = event_enum(text0), values[0] end',
      '            end',
      '            events[#events + 1] = value',
      '        end',
      '        return events',
      '    end)',
      '    local released = clib.galfus_platform_release_event_batch(batch.batch_id)',
      '    if released ~= 0 then error("platformReleaseEventBatch failed: " .. (M.get_last_error() or "unknown")) end',
      '    if not ok then error(events_or_error) end',
      '    return events_or_error',
      'end',
      ''
    );

    for (const fn of context.functions) {
      const luaFuncName = toSnakeCase(fn.methodName);
      const outParam = fn.params.find((p) => p.out && isNativeStruct(p.type));
      const outStruct =
        outParam && isNativeStruct(outParam.type) ? outParam.type.nativeStruct : undefined;
      const paramNames = fn.params
        .filter((p) => !p.out)
        .map((p) => toSnakeCase(p.name))
        .join(', ');

      lines.push(`--- ${fn.doc}`);
      lines.push(`function M.${luaFuncName}(${paramNames})`);

      const callArgParts: string[] = [];
      for (const p of fn.params) {
        const name = toSnakeCase(p.name);
        if (p.out && isNativeStruct(p.type)) {
          lines.push(`    local ${name} = ffi.new("Galfus${p.type.nativeStruct}")`);
          callArgParts.push(name);
        } else if (isNativeStruct(p.type)) {
          const encoder =
            p.type.nativeStruct === 'Transform3D'
              ? 'encode_transform_3d'
              : p.type.nativeStruct === 'Transform2D'
                ? 'encode_transform_2d'
                : p.type.nativeStruct === 'CameraLookAt3D'
                  ? 'encode_camera_look_at_3d'
                  : 'encode_spatial_audio';
          lines.push(`    local _${name} = ${encoder}(${name})`);
          callArgParts.push(`_${name}`);
        } else {
          callArgParts.push(name);
        }
      }
      const callArgs = callArgParts.join(', ');

      if (outParam) {
        lines.push(`    local res = clib.${fn.cName}(${callArgs})`);
        lines.push(`    if res ~= 0 then`);
        lines.push(
          `        error("${fn.methodName} failed: " .. (M.get_last_error() or "unknown"))`
        );
        lines.push(`    end`);
        const decoder =
          outStruct === 'Transform3D'
            ? 'decode_transform_3d'
            : outStruct === 'Transform2D'
              ? 'decode_transform_2d'
              : outStruct === 'EventBatch'
                ? 'decode_event_batch'
                : 'decode_camera_look_at_3d';
        lines.push(`    return ${decoder}(${toSnakeCase(outParam.name)})`);
      } else if (
        isJson(fn.returnType) ||
        isJsonArray(fn.returnType) ||
        fn.returnType === 'string'
      ) {
        lines.push(`    return consume_string(clib.${fn.cName}(${callArgs}))`);
      } else if (fn.returnType === 'i32') {
        lines.push(`    local res = clib.${fn.cName}(${callArgs})`);
        lines.push(`    if res ~= 0 then`);
        lines.push(
          `        error("${fn.methodName} failed: " .. (M.get_last_error() or "unknown"))`
        );
        lines.push(`    end`);
        if (fn.returnsParamField) {
          lines.push(`    return 0`);
        }
      } else if (fn.errorSentinel !== undefined) {
        lines.push(`    local result = clib.${fn.cName}(${callArgs})`);
        lines.push(`    if result == ${fn.errorSentinel} then`);
        lines.push(
          `        error("${fn.methodName} failed: " .. (M.get_last_error() or "unknown"))`
        );
        lines.push(`    end`);
        lines.push(`    return result`);
      } else {
        lines.push(`    return clib.${fn.cName}(${callArgs})`);
      }

      lines.push('end');
      lines.push('');
    }

    lines.push('return M');
    lines.push('');

    return lines.join('\n');
  }
}
