export function fromQuat(out: Mat4, q: ReadonlyQuat): Mat4 {
  const x = q[0];
  const y = q[1];
  const z = q[2];
  const w = q[3];
  const x2 = x + x;
  const y2 = y + y;
  const z2 = z + z;

  const xx = x * x2;
  const yx = y * x2;
  const yy = y * y2;
  const zx = z * x2;
  const zy = z * y2;
  const zz = z * z2;
  const wx = w * x2;
  const wy = w * y2;
  const wz = w * z2;

  out[0] = 1 - yy - zz;
  out[1] = yx + wz;
  out[2] = zx - wy;
  out[3] = 0;

  out[4] = yx - wz;
  out[5] = 1 - xx - zz;
  out[6] = zy + wx;
  out[7] = 0;

  out[8] = zx + wy;
  out[9] = zy - wx;
  out[10] = 1 - xx - yy;
  out[11] = 0;

  out[12] = 0;
  out[13] = 0;
  out[14] = 0;
  out[15] = 1;
  return out;
}

export function fromRotationTranslationScale(
  out: Mat4,
  q: ReadonlyQuat,
  v: ReadonlyVec3,
  s: ReadonlyVec3
): Mat4 {
  const x = q[0];
  const y = q[1];
  const z = q[2];
  const w = q[3];
  const x2 = x + x;
  const y2 = y + y;
  const z2 = z + z;

  const xx = x * x2;
  const xy = x * y2;
  const xz = x * z2;
  const yy = y * y2;
  const yz = y * z2;
  const zz = z * z2;
  const wx = w * x2;
  const wy = w * y2;
  const wz = w * z2;
  const sx = s[0];
  const sy = s[1];
  const sz = s[2];

  out[0] = (1 - (yy + zz)) * sx;
  out[1] = (xy + wz) * sx;
  out[2] = (xz - wy) * sx;
  out[3] = 0;
  out[4] = (xy - wz) * sy;
  out[5] = (1 - (xx + zz)) * sy;
  out[6] = (yz + wx) * sy;
  out[7] = 0;
  out[8] = (xz + wy) * sz;
  out[9] = (yz - wx) * sz;
  out[10] = (1 - (xx + yy)) * sz;
  out[11] = 0;
  out[12] = v[0];
  out[13] = v[1];
  out[14] = v[2];
  out[15] = 1;
  return out;
}

export function translate(out: Mat4, a: ReadonlyMat4, v: ReadonlyVec3): Mat4 {
  const x = v[0];
  const y = v[1];
  const z = v[2];

  if (a === out) {
    out[12] = a[0] * x + a[4] * y + a[8] * z + a[12];
    out[13] = a[1] * x + a[5] * y + a[9] * z + a[13];
    out[14] = a[2] * x + a[6] * y + a[10] * z + a[14];
    out[15] = a[3] * x + a[7] * y + a[11] * z + a[15];
    out[0] = a[0];
    out[1] = a[1];
    out[2] = a[2];
    out[3] = a[3];
    out[4] = a[4];
    out[5] = a[5];
    out[6] = a[6];
    out[7] = a[7];
    out[8] = a[8];
    out[9] = a[9];
    out[10] = a[10];
    out[11] = a[11];
    out[12] = a[0] * x + a[4] * y + a[8] * z + a[12];
    out[13] = a[1] * x + a[5] * y + a[9] * z + a[13];
    out[14] = a[2] * x + a[6] * y + a[10] * z + a[14];
    out[15] = a[3] * x + a[7] * y + a[11] * z + a[15];
  }
  return out;
}

export function scale(out: Mat4, a: ReadonlyMat4, v: ReadonlyVec3): Mat4 {
  const x = v[0];
  const y = v[1];
  const z = v[2];

  out[0] = a[0] * x;
  out[1] = a[1] * x;
  out[2] = a[2] * x;
  out[3] = a[3] * x;
  out[4] = a[4] * y;
  out[5] = a[5] * y;
  out[6] = a[6] * y;
  out[7] = a[7] * y;
  out[8] = a[8] * z;
  out[9] = a[9] * z;
  out[10] = a[10] * z;
  out[11] = a[11] * z;
  out[12] = a[12];
  out[13] = a[13];
  out[14] = a[14];
  out[15] = a[15];
  return out;
}

export function invert(out: Mat4, a: ReadonlyMat4): Mat4 | null {
  const a00 = a[0];
  const a01 = a[1];
  const a02 = a[2];
  const a03 = a[3];
  const a10 = a[4];
  const a11 = a[5];
  const a12 = a[6];
  const a13 = a[7];
  const a20 = a[8];
  const a21 = a[9];
  const a22 = a[10];
  const a23 = a[11];
  const a30 = a[12];
  const a31 = a[13];
  const a32 = a[14];
  const a33 = a[15];

  const b00 = a00 * a11 - a01 * a10;
  const b01 = a00 * a12 - a02 * a10;
  const b02 = a00 * a13 - a03 * a10;
  const b03 = a01 * a12 - a02 * a11;
  const b04 = a01 * a13 - a03 * a11;
  const b05 = a02 * a13 - a03 * a12;
  const b06 = a20 * a31 - a21 * a30;
  const b07 = a20 * a32 - a22 * a30;
  const b08 = a20 * a33 - a23 * a30;
  const b09 = a21 * a32 - a22 * a31;
  const b10 = a21 * a33 - a23 * a31;
  const b11 = a22 * a33 - a23 * a32;

  let det = b00 * b11 - b01 * b10 + b02 * b09 + b03 * b08 - b04 * b07 + b05 * b06;
  if (!det) {
    return null;
  }
  det = 1.0 / det;

  out[0] = (a11 * b11 - a12 * b10 + a13 * b09) * det;
  out[1] = (a02 * b10 - a01 * b11 - a03 * b09) * det;
  out[2] = (a31 * b05 - a32 * b04 + a33 * b03) * det;
  out[3] = (a22 * b04 - a21 * b05 - a23 * b03) * det;
  out[4] = (a12 * b08 - a10 * b11 - a13 * b07) * det;
  out[5] = (a00 * b11 - a02 * b08 + a03 * b07) * det;
  out[6] = (a32 * b02 - a30 * b05 - a33 * b01) * det;
  out[7] = (a20 * b05 - a22 * b02 + a23 * b01) * det;
  out[8] = (a10 * b10 - a11 * b08 + a13 * b06) * det;
  out[9] = (a01 * b08 - a00 * b10 - a03 * b06) * det;
  out[10] = (a30 * b04 - a31 * b02 + a33 * b00) * det;
  out[11] = (a21 * b02 - a20 * b04 - a23 * b00) * det;
  out[12] = (a11 * b07 - a10 * b09 - a12 * b06) * det;
  out[13] = (a00 * b09 - a01 * b07 + a02 * b06) * det;
  out[14] = (a31 * b01 - a30 * b03 - a32 * b00) * det;
  out[15] = (a20 * b03 - a21 * b01 + a22 * b00) * det;
  return out;
}

export function getTranslation(out: Vec3, mat: ReadonlyMat4): Vec3 {
  out[0] = mat[12];
  out[1] = mat[13];
  out[2] = mat[14];
  return out;
}

export function getScaling(out: Vec3, mat: ReadonlyMat4): Vec3 {
  const m11 = mat[0];
  const m12 = mat[1];
  const m13 = mat[2];
  const m21 = mat[4];
  const m22 = mat[5];
  const m23 = mat[6];
  const m31 = mat[8];
  const m32 = mat[9];
  const m33 = mat[10];

  out[0] = Math.hypot(m11, m12, m13);
  out[1] = Math.hypot(m21, m22, m23);
  out[2] = Math.hypot(m31, m32, m33);
  return out;
}

export function getRotation(out: Quat, mat: ReadonlyMat4): Quat {
  const scaling = new Float32Array(3) as unknown as Vec3;
  getScaling(scaling, mat);

  const isx = 1.0 / (scaling[0] || 1);
  const isy = 1.0 / (scaling[1] || 1);
  const isz = 1.0 / (scaling[2] || 1);

  const sm11 = mat[0] * isx;
  const sm12 = mat[1] * isx;
  const sm13 = mat[2] * isx;
  const sm21 = mat[4] * isy;
  const sm22 = mat[5] * isy;
  const sm23 = mat[6] * isy;
  const sm31 = mat[8] * isz;
  const sm32 = mat[9] * isz;
  const sm33 = mat[10] * isz;

  const trace = sm11 + sm22 + sm33;
  let s = 0;

  if (trace > 0) {
    s = Math.sqrt(trace + 1.0) * 2;
    out[3] = 0.25 * s;
    out[0] = (sm23 - sm32) / s;
    out[1] = (sm31 - sm13) / s;
    out[2] = (sm12 - sm21) / s;
  } else if (sm11 > sm22 && sm11 > sm33) {
    s = Math.sqrt(1.0 + sm11 - sm22 - sm33) * 2;
    out[3] = (sm23 - sm32) / s;
    out[0] = 0.25 * s;
    out[1] = (sm12 + sm21) / s;
    out[2] = (sm31 + sm13) / s;
  } else if (sm22 > sm33) {
    s = Math.sqrt(1.0 + sm22 - sm11 - sm33) * 2;
    out[3] = (sm31 - sm13) / s;
    out[0] = (sm12 + sm21) / s;
    out[1] = 0.25 * s;
    out[2] = (sm23 + sm32) / s;
  } else {
    s = Math.sqrt(1.0 + sm33 - sm11 - sm22) * 2;
    out[3] = (sm12 - sm21) / s;
    out[0] = (sm31 + sm13) / s;
    out[1] = (sm23 + sm32) / s;
    out[2] = 0.25 * s;
  }
  return out;
}

export function equals(a: ReadonlyMat4, b: ReadonlyMat4, epsilon: number = EPSILON): boolean {
  return (
    equalsApprox(a[0], b[0], epsilon) &&
    equalsApprox(a[1], b[1], epsilon) &&
    equalsApprox(a[2], b[2], epsilon) &&
    equalsApprox(a[3], b[3], epsilon) &&
    equalsApprox(a[4], b[4], epsilon) &&
    equalsApprox(a[5], b[5], epsilon) &&
    equalsApprox(a[6], b[6], epsilon) &&
    equalsApprox(a[7], b[7], epsilon) &&
    equalsApprox(a[8], b[8], epsilon) &&
    equalsApprox(a[9], b[9], epsilon) &&
    equalsApprox(a[10], b[10], epsilon) &&
    equalsApprox(a[11], b[11], epsilon) &&
    equalsApprox(a[12], b[12], epsilon) &&
    equalsApprox(a[13], b[13], epsilon) &&
    equalsApprox(a[14], b[14], epsilon) &&
    equalsApprox(a[15], b[15], epsilon)
  );
}
