// Regenerate the distributable PNG and its browser-safe embedded representation.
import { writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';

const size = 24;
const image = new PNG({ width: size * 8, height: size * 2 });
const segment = (x: number, y: number, ax: number, ay: number, bx: number, by: number) => {
  const dx = bx - ax,
    dy = by - ay;
  const t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)));
  return Math.hypot(x - ax - t * dx, y - ay - t * dy) < 1.1;
};
const line = (x: number, y: number, points: number[][]) =>
  points
    .slice(1)
    .some((point, i) => segment(x, y, points[i]![0]!, points[i]![1]!, point[0]!, point[1]!));
const ring = (x: number, y: number, cx: number, cy: number, r: number) =>
  Math.abs(Math.hypot(x - cx, y - cy) - r) < 1.1;
const box = (x: number, y: number) =>
  line(x, y, [
    [4, 4],
    [20, 4],
    [20, 20],
    [4, 20],
    [4, 4]
  ]);
const check = (x: number, y: number) =>
  line(x, y, [
    [6, 12],
    [10, 16],
    [18, 8]
  ]);
const switchShape = (x: number, y: number, on: boolean) => {
  const capsule =
    (x >= 8 && x <= 16 && (Math.abs(y - 7) < 1.1 || Math.abs(y - 17) < 1.1)) ||
    (x < 8 && ring(x, y, 8, 12, 5)) ||
    (x > 16 && ring(x, y, 16, 12, 5));
  return capsule || Math.hypot(x - (on ? 16 : 8), y - 12) < 3;
};
const shapes: Array<(x: number, y: number) => boolean> = [
  box,
  (x, y) => box(x, y) || check(x, y),
  (x, y) =>
    box(x, y) ||
    line(x, y, [
      [7, 12],
      [17, 12]
    ]),
  (x, y) => ring(x, y, 12, 12, 8),
  (x, y) => ring(x, y, 12, 12, 8) || Math.hypot(x - 12, y - 12) < 4,
  (x, y) => switchShape(x, y, false),
  (x, y) => switchShape(x, y, true),
  (x, y) =>
    line(x, y, [
      [6, 9],
      [12, 15],
      [18, 9]
    ]),
  (x, y) =>
    line(x, y, [
      [9, 6],
      [15, 12],
      [9, 18]
    ]),
  (x, y) =>
    line(x, y, [
      [6, 15],
      [12, 9],
      [18, 15]
    ]),
  (x, y) =>
    line(x, y, [
      [15, 6],
      [9, 12],
      [15, 18]
    ]),
  check,
  (x, y) =>
    line(x, y, [
      [6, 6],
      [18, 18]
    ]) ||
    line(x, y, [
      [18, 6],
      [6, 18]
    ]),
  (x, y) =>
    [7, 12, 17].some((yy) =>
      line(x, y, [
        [5, yy],
        [19, yy]
      ])
    ),
  (x, y) => [7, 12, 17].some((xx) => Math.hypot(x - xx, y - 12) < 1.5),
  (x, y) =>
    line(x, y, [
      [5, 12],
      [19, 12]
    ]) ||
    line(x, y, [
      [12, 5],
      [12, 19]
    ])
];
for (let i = 0; i < shapes.length; i++) {
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      let coverage = 0;
      for (let sy = 0; sy < 4; sy++)
        for (let sx = 0; sx < 4; sx++)
          if (shapes[i]!(x + (sx + 0.5) / 4, y + (sy + 0.5) / 4)) coverage++;
      const offset = ((Math.floor(i / 8) * size + y) * image.width + (i % 8) * size + x) * 4;
      image.data[offset] = 255;
      image.data[offset + 1] = 255;
      image.data[offset + 2] = 255;
      image.data[offset + 3] = Math.round((coverage * 255) / 16);
    }
}
const png = PNG.sync.write(image);
writeFileSync(new URL('../assets/ui-icons.png', import.meta.url), png);
writeFileSync(
  new URL('../src/icons/embedded.ts', import.meta.url),
  `// Generated by scripts/generate-icons.ts.\nexport const UI_ICONS_PNG_BASE64 =\n  '${png.toString('base64')}';\n`
);
